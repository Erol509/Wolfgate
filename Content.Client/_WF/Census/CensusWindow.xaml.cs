using System.Linq;
using Content.Client.Message;
using Content.Shared._WF.Census;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._WF.Census;

/// <summary>The open censuses, and the questions of the one the player picked to answer.</summary>
[GenerateTypedNameReferences]
public sealed partial class CensusWindow : DefaultWindow
{
    private readonly List<CensusQuestionControl> _questions = new();
    private CensusEntry? _open;
    private bool _sending;

    /// <summary>Raised with answers that pass the checks the client can make.</summary>
    public event Action<CensusSubmitEvent>? Submitted;

    public CensusWindow()
    {
        RobustXamlLoader.Load(this);
        BackButton.OnPressed += _ => ShowList();
        SubmitButton.OnPressed += _ => Submit();
        RequiredNote.SetMarkup(Loc.GetString("wf-census-required-note"));
    }

    /// <summary>Shows the open censuses. A census being answered stays open unless it has gone.</summary>
    public void SetCensuses(List<CensusEntry> censuses)
    {
        CensusList.RemoveAllChildren();
        ListNote.Text = Loc.GetString("wf-census-list-empty");
        ListNote.Visible = censuses.Count == 0;
        for (var i = 0; i < censuses.Count; i++)
        {
            CensusList.AddChild(BuildRow(censuses[i], i));
        }

        if (_open == null)
            return;

        var current = censuses.FirstOrDefault(c => c.Id == _open.Id);
        if (current == null || current.Answered)
        {
            if (!_sending)
                ShowList();
            if (current == null)
                SetStatus("wf-census-error-not-open");
        }
    }

    /// <summary>Shows the server's answer to the last submission.</summary>
    public void ShowResult(CensusResultEvent ev)
    {
        _sending = false;
        SubmitButton.Disabled = false;
        if (ev.Error == null)
        {
            ShowList();
            StatusLabel.SetMarkup(Loc.GetString("wf-census-sent"));
            return;
        }

        StatusLabel.SetMarkup(Loc.GetString(ev.Error,
            ("question", FormattedMessage.EscapeText(ev.Question)),
            ("count", ev.Count)));
        if (ev.Error is "wf-census-error-answered" or "wf-census-error-not-open")
            ShowList();
    }

    // A row each, striped, with a rule under it, as the game's other lists.
    private static PanelContainer RowPanel(int index, Control content)
    {
        var panel = new PanelContainer
        {
            HorizontalExpand = true,
            PanelOverride = new StyleBoxFlat
            {
                BackgroundColor = Color.FromHex(index % 2 == 0 ? "#1e1e22" : "#19191c"),
                BorderColor = Color.FromHex("#333333"),
                BorderThickness = new Thickness(0, 0, 0, 1),
                ContentMarginLeftOverride = 10,
                ContentMarginRightOverride = 10,
                ContentMarginTopOverride = 8,
                ContentMarginBottomOverride = 8,
            },
        };
        panel.AddChild(content);
        return panel;
    }

    private Control BuildRow(CensusEntry census, int index)
    {
        var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, HorizontalExpand = true, SeparationOverride = 12 };
        var text = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, HorizontalExpand = true, SeparationOverride = 2 };

        var title = new RichTextLabel();
        title.SetMessage(FormattedMessage.FromMarkupPermissive($"[bold]{FormattedMessage.EscapeText(census.Title)}[/bold]"));
        text.AddChild(title);

        if (census.Description.Length > 0)
        {
            var description = new RichTextLabel();
            description.SetMessage(FormattedMessage.FromUnformatted(census.Description));
            text.AddChild(description);
        }

        if (census.ClosesAt is { } closes)
        {
            text.AddChild(new Label
            {
                Text = Loc.GetString("wf-census-closes-in", ("time", TimeLeft(closes))),
                StyleClasses = { "LabelSubText" },
            });
        }

        row.AddChild(text);
        if (census.Answered)
        {
            row.AddChild(new Label
            {
                Text = Loc.GetString("wf-census-answered"),
                FontColorOverride = Color.FromHex("#7fd17f"),
                VerticalAlignment = VAlignment.Center,
            });
        }
        else
        {
            var answer = new Button { Text = Loc.GetString("wf-census-answer"), VerticalAlignment = VAlignment.Center, MinWidth = 90 };
            answer.OnPressed += _ => ShowForm(census);
            row.AddChild(answer);
        }

        return RowPanel(index, row);
    }

    private static string TimeLeft(DateTime closes)
    {
        var left = closes - DateTime.UtcNow;
        if (left.TotalDays >= 1)
            return Loc.GetString("wf-census-time-days", ("count", (int) left.TotalDays));
        if (left.TotalHours >= 1)
            return Loc.GetString("wf-census-time-hours", ("count", (int) left.TotalHours));
        return Loc.GetString("wf-census-time-minutes", ("count", Math.Max(1, (int) Math.Ceiling(left.TotalMinutes))));
    }

    private void ShowList()
    {
        _open = null;
        _questions.Clear();
        QuestionList.RemoveAllChildren();
        FormBox.Visible = false;
        ListBox.Visible = true;
        StatusLabel.SetMessage(FormattedMessage.Empty);
    }

    private void ShowForm(CensusEntry census)
    {
        _open = census;
        _questions.Clear();
        QuestionList.RemoveAllChildren();
        FormTitle.SetMessage(FormattedMessage.FromMarkupPermissive($"[bold]{FormattedMessage.EscapeText(census.Title)}[/bold]"));
        FormDescription.SetMessage(FormattedMessage.FromUnformatted(census.Description));
        FormDescription.Visible = census.Description.Length > 0;
        foreach (var question in census.Questions)
        {
            var control = new CensusQuestionControl(question);
            _questions.Add(control);
            QuestionList.AddChild(RowPanel(_questions.Count - 1, control));
        }

        RequiredNote.Visible = census.Questions.Any(q => q.Required);
        StatusLabel.SetMessage(FormattedMessage.Empty);
        SubmitButton.Disabled = false;
        ListBox.Visible = false;
        FormBox.Visible = true;
    }

    private void Submit()
    {
        if (_open == null || _sending)
            return;

        var answers = new CensusSubmitEvent { CensusId = _open.Id };
        foreach (var question in _questions)
        {
            if (question.Collect(answers) is { } problem)
            {
                StatusLabel.SetMarkup(problem);
                return;
            }
        }

        _sending = true;
        SubmitButton.Disabled = true;
        SetStatus("wf-census-sending");
        Submitted?.Invoke(answers);
    }

    private void SetStatus(string id)
    {
        StatusLabel.SetMarkup(Loc.GetString(id));
    }
}
