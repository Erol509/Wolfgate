using System.Text;
using Content.Client.UserInterface.Controls;
using Content.Shared._WF.Remade;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.ResourceManagement;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Random;
using Robust.Shared.Timing;
using Robust.Shared.Utility;

namespace Content.Client._WF.Remade;

/// <summary>Shows a Monolith's resonance, a dial and a line for each Gift, and what the stone is doing, carved in its own writing.</summary>
[GenerateTypedNameReferences]
public sealed partial class WFMonolithTapWindow : FancyWindow
{
    /// <summary>Width the descriptions wrap at, inside the window's margins.</summary>
    public const float TextWidth = 460f;

    private const string GlyphLetters = "ABCDEFGHIJKLMNOPQRSTUVWXYZ";
    private const int StripLength = 34;

    private static readonly int[] DialSteps = { 0, 25, 50, 75, 100 };
    private static readonly WFGift[] Gifts = { WFGift.Power, WFGift.Matter, WFGift.Flesh, WFGift.Reach, WFGift.Ward };

    public event Action<WFGift, float>? OnDial;

    private readonly IRobustRandom _random;
    private readonly WFGlyphButton[][] _buttons = new WFGlyphButton[Gifts.Length][];
    private readonly PanelContainer[] _slabs = new PanelContainer[Gifts.Length];
    private readonly Label[] _sigils = new Label[Gifts.Length];
    private readonly Label[] _strips;
    private readonly char[][] _stripText;

    private WFMonolithStage _stage = WFMonolithStage.Quiet;
    private float _sinceShift;

    public WFMonolithTapWindow()
    {
        RobustXamlLoader.Load(this);
        var cache = IoCManager.Resolve<IResourceCache>();
        _random = IoCManager.Resolve<IRobustRandom>();

        var glyphs = WFMonolithTheme.Glyphs(cache, 14);
        var text = WFMonolithTheme.Text(cache, 13);

        CarveChrome(WFMonolithTheme.Text(cache, 15));
        Body.PanelOverride = WFMonolithTheme.Panel(WFMonolithTheme.Stone, WFMonolithTheme.Stone);
        WarningPanel.PanelOverride = WFMonolithTheme.Panel(Color.FromHex("#120606"), WFMonolithTheme.Seam, 1f, 8f);

        StageLabel.FontOverride = WFMonolithTheme.Text(cache, 26);
        ResonanceLabel.FontOverride = text;
        ResonanceLabel.FontColorOverride = WFMonolithTheme.Bone;
        ClimbLabel.FontOverride = text;
        ClimbLabel.FontColorOverride = WFMonolithTheme.Ash;
        NoteLabel.FontOverride = WFMonolithTheme.Text(cache, 11);
        NoteLabel.FontColorOverride = WFMonolithTheme.Ash;
        ResonanceBar.BackgroundStyleBoxOverride = WFMonolithTheme.Panel(Color.FromHex("#160807"), WFMonolithTheme.Seam);

        _strips = new[] { GlyphTop, GlyphStage, GlyphBottom };
        _stripText = new char[_strips.Length][];
        for (var i = 0; i < _strips.Length; i++)
        {
            _strips[i].FontOverride = i == 1 ? WFMonolithTheme.Glyphs(cache, 10) : glyphs;
            _stripText[i] = new char[StripLength];
            for (var c = 0; c < StripLength; c++)
            {
                _stripText[i][c] = RandomGlyph();
            }

            _strips[i].Text = new string(_stripText[i]);
        }

        for (var g = 0; g < Gifts.Length; g++)
        {
            BuildGift(g, cache, text);
        }

        Recolour();
    }

    /// <summary>Repaints the window's frame as the stone: black with a red seam, the title in the stone's own lettering.</summary>
    private void CarveChrome(Font titleFont)
    {
        if (ChildCount < 2 || GetChild(0) is not PanelContainer frame || GetChild(1) is not BoxContainer column)
            return;

        frame.PanelOverride = WFMonolithTheme.Panel(WFMonolithTheme.Stone, WFMonolithTheme.Vein, 2f);
        foreach (var child in column.Children)
        {
            if (child is PanelContainer divider)
            {
                divider.PanelOverride = WFMonolithTheme.Panel(WFMonolithTheme.Vein, WFMonolithTheme.Vein);
                continue;
            }

            foreach (var part in child.Children)
            {
                if (part is PanelContainer heading)
                    heading.PanelOverride = WFMonolithTheme.Panel(Color.FromHex("#120706"), Color.FromHex("#120706"));

                foreach (var label in part.Children)
                {
                    if (label is not Label title)
                        continue;

                    title.FontOverride = titleFont;
                    title.FontColorOverride = WFMonolithTheme.Ember;
                }
            }
        }
    }

    private void BuildGift(int g, IResourceCache cache, Font text)
    {
        var gift = Gifts[g];
        var slab = new PanelContainer { HorizontalExpand = true };
        var line = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 10 };

        // The Gift's sigil: its initial in the stone's writing.
        var sigil = new Label
        {
            Text = Loc.GetString($"wf-monolith-gift-{GiftKey(gift)}")[..1].ToUpperInvariant(),
            FontOverride = WFMonolithTheme.Glyphs(cache, 34),
            VerticalAlignment = VAlignment.Center,
            MinWidth = 40,
            Align = Label.AlignMode.Center,
        };

        var column = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, SeparationOverride = 2, HorizontalExpand = true };
        var top = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 4, HorizontalExpand = true };
        var name = new Label
        {
            Text = Loc.GetString($"wf-monolith-gift-{GiftKey(gift)}").ToUpperInvariant(),
            FontOverride = WFMonolithTheme.Text(cache, 16),
            FontColorOverride = WFMonolithTheme.Bone,
            MinWidth = 86,
            VerticalAlignment = VAlignment.Center,
        };
        top.AddChild(name);

        var group = new ButtonGroup();
        _buttons[g] = new WFGlyphButton[DialSteps.Length];
        for (var i = 0; i < DialSteps.Length; i++)
        {
            var step = DialSteps[i];
            var button = new WFGlyphButton(text)
            {
                Text = Loc.GetString("wf-monolith-tap-draw-step", ("percent", step)),
                HorizontalExpand = true,
                MinHeight = 24,
                ToggleMode = true,
                Group = group,
            };
            button.OnPressed += _ => OnDial?.Invoke(gift, step / 100f);
            _buttons[g][i] = button;
            top.AddChild(button);
        }

        column.AddChild(top);
        line.AddChild(sigil);
        line.AddChild(column);
        slab.AddChild(line);
        GiftRows.AddChild(slab);

        _slabs[g] = slab;
        _sigils[g] = sigil;
    }

    private static string GiftKey(WFGift gift) => gift.ToString().ToLowerInvariant();

    private char RandomGlyph()
    {
        // A few gaps break the writing into words.
        return _random.Prob(0.18f) ? ' ' : GlyphLetters[_random.Next(GlyphLetters.Length)];
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        // The writing shifts faster the louder the stone gets.
        _sinceShift += args.DeltaSeconds;
        var every = 0.9f - 0.14f * (int) _stage;
        if (_sinceShift < every)
            return;

        _sinceShift = 0f;
        for (var i = 0; i < _strips.Length; i++)
        {
            for (var n = 0; n <= (int) _stage / 2; n++)
            {
                _stripText[i][_random.Next(StripLength)] = RandomGlyph();
            }

            _strips[i].Text = new string(_stripText[i]);
        }
    }

    public void UpdateState(WFMonolithTapState state)
    {
        if (state.Resonance is not { } resonance)
        {
            _stage = WFMonolithStage.Quiet;
            StageLabel.Text = Loc.GetString("wf-monolith-tap-no-scion");
            ResonanceLabel.Text = string.Empty;
            ResonanceBar.Value = 0f;
            ClimbLabel.Text = string.Empty;
            NoteLabel.Text = string.Empty;
            WarningLabel.SetMessage(FormattedMessage.Empty);
            for (var g = 0; g < Gifts.Length; g++)
            {
                SetButtons(g, false, 0);
            }

            Recolour();
            return;
        }

        _stage = state.Stage;
        var rooted = state.Stage == WFMonolithStage.Crescendo;
        StageLabel.Text = Loc.GetString($"wf-monolith-stage-{state.Stage.ToString().ToLowerInvariant()}").ToUpperInvariant();
        ResonanceLabel.Text = Loc.GetString("wf-monolith-tap-resonance", ("resonance", Round(resonance, 1)));
        ResonanceBar.Value = resonance;
        ClimbLabel.Text = Loc.GetString("wf-monolith-tap-climb", ("rate", Round(state.Climb, 1)));

        for (var g = 0; g < Gifts.Length; g++)
        {
            var gift = Gifts[g];
            var dial = state.Dial(gift);
            // A rooted stone holds every Gift but Power at full, and the dial can't be moved.
            var locked = rooted && gift != WFGift.Power;
            SetButtons(g, !state.Barred && !locked, (int) MathF.Round(dial * 100f));
            _slabs[g].PanelOverride = WFMonolithTheme.Etched(dial > 0f ? WFMonolithTheme.StageColor(_stage) : WFMonolithTheme.Seam, 3f);
            _sigils[g].FontColorOverride = dial > 0f ? WFMonolithTheme.StageColor(_stage) : WFMonolithTheme.DeadGlyph;
        }

        WarningLabel.SetMessage(Tint(Warnings(state), WFMonolithTheme.Bone));
        NoteLabel.Text = state.Barred
            ? Loc.GetString("wf-monolith-tap-barred")
            : Loc.GetString("wf-monolith-tap-feed-hint");
        Recolour();
    }

    /// <summary>Lights the stage name, the bar and the writing in the stone's colour.</summary>
    private void Recolour()
    {
        var colour = WFMonolithTheme.StageColor(_stage);
        StageLabel.FontColorOverride = colour;
        ResonanceBar.ForegroundStyleBoxOverride = WFMonolithTheme.Panel(colour, colour);
        GlyphTop.FontColorOverride = colour.WithAlpha(0.55f);
        GlyphStage.FontColorOverride = colour.WithAlpha(0.8f);
        GlyphBottom.FontColorOverride = colour.WithAlpha(0.35f);
    }

    /// <summary>Rounded as a double, so a float doesn't print its last few noisy digits.</summary>
    private static double Round(float value, int digits) => Math.Round((double) value, digits);

    private static FormattedMessage Tint(string text, Color colour)
    {
        var message = new FormattedMessage();
        message.PushColor(colour);
        message.AddText(text);
        message.Pop();
        return message;
    }

    /// <summary>A plain warning of what the stone is doing.</summary>
    private static string Warnings(WFMonolithTapState state)
    {
        var text = new StringBuilder();
        text.Append(Loc.GetString($"wf-monolith-warning-{state.Stage.ToString().ToLowerInvariant()}"));
        if (state.Dial(WFGift.Flesh) > 0f)
            text.Append(' ').Append(Loc.GetString("wf-monolith-warning-flesh"));

        if (state.Shards > 0)
            text.Append(' ').Append(Loc.GetString("wf-monolith-warning-shards", ("count", state.Shards)));

        return text.ToString();
    }

    private void SetButtons(int gift, bool enabled, int percent)
    {
        for (var i = 0; i < DialSteps.Length; i++)
        {
            _buttons[gift][i].Disabled = !enabled;
            _buttons[gift][i].Pressed = DialSteps[i] == percent;
        }
    }
}
