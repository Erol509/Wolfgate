/// <summary>Recreates the /tg/ TGUI MODsuit interface in the SS14 UI toolkit.</summary>
[GenerateTypedNameReferences]
public sealed partial class ModSuitWindow : FancyWindow
{
    [Dependency] private IEntityManager _entMan = default!;
    [Dependency] private IPrototypeManager _proto = default!;
    [Dependency] private IGameTiming _timing = default!;
    [Dependency] private IResourceCache _cache = default!;

    private ModSuitSystem _modSuit = default!;
    private InventorySystem _inventory = default!;
    private RSI? _iconRsi;

    private EntityUid _suit;
    private TimeSpan _chargeAccumulator;
    private bool _modulesBuilt;
    private bool _hardwareBuilt;

    private readonly Dictionary<EntityUid, ModuleRow> _moduleRows = new();
    private readonly Dictionary<string, (ModSuitIconButton Button, Label Value)> _partRows = new();
    private Label? _controlValue;
    private Label? _coreValue;
    private Label? _aiValue;

    private const int ActionButtonWidth = 42;
    private const int ValueColumnWidth = 34;
    private const int LabelColumnWidth = 96;
    private static readonly ResPath IconRsiPath = new("/Textures/_WF/Modsuits/icons.rsi");

    private static readonly Color PrimaryColor = Color.FromHex("#3E5774");
    private static readonly Color LabelColor = Color.FromHex("#8091A6");
    private static readonly Color GoodColor = Color.FromHex("#5BA626");
    private static readonly Color AverageColor = Color.FromHex("#E59A1A");
    private static readonly Color BadColor = Color.FromHex("#DC2323");
    private static readonly Color DimColor = Color.FromHex("#00000080");

    public event Action? OnActivate;
    public event Action<string>? OnTogglePart;
    public event Action<NetEntity>? OnModuleToggle;
    public event Action<NetEntity>? OnModulePin;
    public event Action<NetEntity>? OnModuleRemove;

    public ModSuitWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _iconRsi = _cache.GetResource<RSIResource>(IconRsiPath).RSI;
        SetButtonIcon(ActivateButton, "power-off");
        SetButtonIcon(IdLockButton, "lock-open");
        SetButtonIcon(ModLinkButton, "wifi");

        ActivateButton.OnPressed += _ => OnActivate?.Invoke();
        StyleButton(ActivateButton);
        StyleButton(IdLockButton);
        StyleButton(ModLinkButton);
        IdLockButton.ModulateSelfOverride = new Color(1, 1, 1, 0.5f);
        ModLinkButton.ModulateSelfOverride = new Color(1, 1, 1, 0.5f);

        BuildModulesHeader();
    }

    public void SetSuit(EntityUid suit)
    {
        _suit = suit;
        _modSuit = _entMan.System<ModSuitSystem>();
        _inventory = _entMan.System<InventorySystem>();

        _modulesBuilt = false;
        _hardwareBuilt = false;
        _moduleRows.Clear();
        _partRows.Clear();
        ModulesList.RemoveAllChildren();
        HardwareList.RemoveAllChildren();

        Refresh();
    }

    public void Refresh()
    {
        if (!_entMan.TryGetComponent<ModSuitComponent>(_suit, out var suit))
            return;

        var ent = (_suit, suit);
        var state = suit.State;

        ActivateButton.Text = Loc.GetString($"modsuit-ui-state-{state.ToString().ToLowerInvariant()}");
        StyleButton(ActivateButton, state == ModSuitState.Active ? GoodColor : PrimaryColor);

        CoverRow.Visible = _entMan.TryGetComponent<WiresPanelComponent>(_suit, out var panel) && panel.Open;

        UpdateCharge(ent);
        UpdateUserStatus(ent);
        UpdateModules(ent);
        UpdateHardware(ent);
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        _chargeAccumulator += TimeSpan.FromSeconds(args.DeltaSeconds);
        if (_chargeAccumulator < TimeSpan.FromSeconds(0.5))
            return;

        _chargeAccumulator = TimeSpan.Zero;
        if (_entMan.TryGetComponent<ModSuitComponent>(_suit, out var suit))
            UpdateCharge((_suit, suit));

        CoverRow.Visible = _entMan.TryGetComponent<WiresPanelComponent>(_suit, out var panel) && panel.Open;
    }

    private void UpdateCharge(Entity<ModSuitComponent> suit)
    {
        var hasCore = _modSuit.GetCore(suit) != null;
        var hasCell = _modSuit.GetBattery(suit) != null;
        var ratio = hasCell
            ? Math.Clamp(suit.Comp.Charge / MathF.Max(1f, suit.Comp.MaxCharge), 0f, 1f)
            : 0f;

        ChargeBar.Value = ratio;

        var color = ratio <= 0.33f ? BadColor : ratio < 0.66f ? AverageColor : GoodColor;
        ChargeBorder.PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = DimColor,
            BorderColor = color,
            BorderThickness = new Thickness(1),
        };
        ChargeBar.ForegroundStyleBoxOverride = new StyleBoxFlat(color);
        ChargeBar.BackgroundStyleBoxOverride = new StyleBoxFlat(new Color(0, 0, 0, 0));

        if (!hasCore)
        {
            ChargeText.Text = Loc.GetString("modsuit-ui-no-core-detected");
            return;
        }

        if (!hasCell)
        {
            ChargeText.Text = Loc.GetString("modsuit-ui-cell-missing");
            return;
        }

        ChargeText.Text = Loc.GetString("modsuit-ui-charge-bar",
            ("current", (int) MathF.Round(suit.Comp.Charge)),
            ("max", (int) MathF.Round(suit.Comp.MaxCharge)),
            ("percent", (int) MathF.Round(ratio * 100f)));
    }

    private void UpdateUserStatus(Entity<ModSuitComponent> suit)
    {
        if (suit.Comp.Wearer is { } wearer && _entMan.EntityExists(wearer))
        {
            UserNameLabel.Text = _entMan.GetComponent<MetaDataComponent>(wearer).EntityName;
            UserAssignmentLabel.Text = GetAssignment(wearer);
        }
        else
        {
            UserNameLabel.Text = string.Empty;
            UserAssignmentLabel.Text = string.Empty;
        }

        UserDimmer.Visible = suit.Comp.State != ModSuitState.Active;
    }

    private string GetAssignment(EntityUid wearer)
    {
        if (!_inventory.TryGetSlotEntity(wearer, "id", out var id)
            || !_entMan.TryGetComponent<IdCardComponent>(id, out var card))
            return string.Empty;

        return card.LocalizedJobTitle ?? string.Empty;
    }

    private void UpdateModules(Entity<ModSuitComponent> suit)
    {
        var modulesContainer = suit.Comp.ModulesContainer;
        var modules = modulesContainer.ContainedEntities.ToList();
        ModulesHeader.Visible = modules.Count > 0;

        if (!_modulesBuilt || !modules.SequenceEqual(_moduleRows.Keys))
        {
            _modulesBuilt = true;
            ModulesList.RemoveAllChildren();
            _moduleRows.Clear();

            if (modules.Count == 0)
            {
                ModulesList.AddChild(new Label
                {
                    Text = Loc.GetString("modsuit-ui-no-modules-detected"),
                    FontColorOverride = LabelColor,
                });
            }

            foreach (var module in modules)
            {
                if (!_entMan.TryGetComponent<ModModuleComponent>(module, out var moduleComp))
                    continue;

                var row = BuildModuleRow(module, moduleComp);
                ModulesList.AddChild(row.Root);
                _moduleRows[module] = row;
            }
        }

        foreach (var (module, row) in _moduleRows)
        {
            if (_entMan.TryGetComponent<ModModuleComponent>(module, out var moduleComp))
                UpdateModuleRow(row, moduleComp);
        }

        ModulesInfoLabel.Text = Loc.GetString("modsuit-ui-complexity-used",
            ("current", _modSuit.GetComplexity(suit)),
            ("max", _proto.Index(suit.Comp.Theme).ComplexityMax));
    }

    private ModuleRow BuildModuleRow(EntityUid module, ModModuleComponent moduleComp)
    {
        var netModule = _entMan.GetNetEntity(module);
        var meta = _entMan.GetComponent<MetaDataComponent>(module);

        var root = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            SeparationOverride = 2,
        };

        var select = new ModSuitIconButton
        {
            MinWidth = ActionButtonWidth,
            ClipText = true,
            IconOnly = true,
            ToolTip = Loc.GetString("modsuit-ui-select"),
        };
        select.OnPressed += _ => OnModuleToggle?.Invoke(netModule);

        var eject = new ModSuitIconButton
        {
            MinWidth = ActionButtonWidth,
            ClipText = true,
            IconOnly = true,
            ToolTip = Loc.GetString("modsuit-ui-module-remove"),
        };
        eject.OnPressed += _ => OnModuleRemove?.Invoke(netModule);

        var pin = new ModSuitIconButton
        {
            MinWidth = ActionButtonWidth,
            ClipText = true,
            IconOnly = true,
            ToolTip = Loc.GetString("modsuit-ui-pin"),
        };
        pin.OnPressed += _ => OnModulePin?.Invoke(netModule);

        SetButtonIcon(select, "power-off");
        SetButtonIcon(eject, "eject");
        SetButtonIcon(pin, "thumbtack");

        root.AddChild(select);
        root.AddChild(eject);
        root.AddChild(pin);

        var nameBox = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
        };

        var heading = new CollapsibleHeading(meta.EntityName)
        {
            MinHeight = 18,
            StyleBoxOverride = new StyleBoxFlat(new Color(0, 0, 0, 0)),
        };
        heading.Label.FontColorOverride = Color.White;

        var body = new CollapsibleBody();
        var description = new RichTextLabel
        {
            HorizontalExpand = true,
            Margin = new Thickness(12, 2, 0, 2),
        };
        description.SetMessage(meta.EntityDescription);
        body.AddChild(description);

        nameBox.AddChild(new Collapsible(heading, body));
        root.AddChild(nameBox);

        var idle = MakeValueLabel();
        var active = MakeValueLabel();
        var use = MakeValueLabel();
        var complexity = MakeValueLabel();
        root.AddChild(idle);
        root.AddChild(active);
        root.AddChild(use);
        root.AddChild(complexity);

        StyleButton(select);
        StyleButton(eject);
        StyleButton(pin);

        return new ModuleRow(root, select, eject, pin, heading, idle, active, use, complexity);
    }

    private void UpdateModuleRow(ModuleRow row, ModModuleComponent module)
    {
        var disabled = module.Type == ModModuleType.Passive || module.NextUse > _timing.CurTime;
        row.Select.ToolTip = module.Type == ModModuleType.Usable
            ? Loc.GetString("modsuit-ui-module-use")
            : Loc.GetString(module.Active ? "modsuit-ui-module-off" : "modsuit-ui-module-on");
        SetButtonIcon(row.Select, module.Type == ModModuleType.Active
            ? module.Active ? "check-square-o" : "square-o"
            : "power-off");
        row.Select.Disabled = disabled;
        row.Select.ModulateSelfOverride = disabled ? new Color(1, 1, 1, 0.5f) : Color.White;
        StyleButton(row.Select, module.Active ? GoodColor : PrimaryColor);

        row.Eject.Disabled = !module.Removable;
        row.Eject.ModulateSelfOverride = row.Eject.Disabled ? new Color(1, 1, 1, 0.5f) : Color.White;
        StyleButton(row.Eject);

        row.Pin.ToolTip = Loc.GetString(module.Pinned ? "modsuit-ui-unpin" : "modsuit-ui-pin");
        row.Pin.Disabled = module.Type == ModModuleType.Passive;
        row.Pin.ModulateSelfOverride = row.Pin.Disabled ? new Color(1, 1, 1, 0.5f) : Color.White;
        StyleButton(row.Pin, module.Pinned ? GoodColor : PrimaryColor);

        row.Heading.Label.FontColorOverride = module.Active ? GoodColor : Color.White;
        var idlePower = module.IdlePower;
        var activePower = module.ActivePower;
        var usePower = module.UsePower;
        var complexity = module.Complexity;
        row.Idle.Text = idlePower.ToString("0.##");
        row.ActivePower.Text = activePower.ToString("0.##");
        row.Use.Text = usePower.ToString("0.##");
        row.Complexity.Text = complexity.ToString();
    }

    private void BuildModulesHeader()
    {
        ModulesHeader.RemoveAllChildren();

        ModulesHeader.AddChild(new Label
        {
            Text = Loc.GetString("modsuit-ui-actions"),
            MinWidth = ActionButtonWidth * 3 + 4,
            StyleClasses = { "LabelKeyText" },
            FontColorOverride = LabelColor,
            VerticalAlignment = VAlignment.Center,
        });

        ModulesHeader.AddChild(new Label
        {
            Text = Loc.GetString("modsuit-ui-name"),
            HorizontalExpand = true,
            StyleClasses = { "LabelKeyText" },
            FontColorOverride = LabelColor,
            VerticalAlignment = VAlignment.Center,
        });

        AddHeaderIcon("plug", "modsuit-ui-idle-power");
        AddHeaderIcon("lightbulb", "modsuit-ui-active-power");
        AddHeaderIcon("bolt", "modsuit-ui-use-power");
        AddHeaderIcon("save", "modsuit-ui-module-complexity");
    }

    private void AddHeaderIcon(string icon, string tooltip)
    {
        ModulesHeader.AddChild(new TextureRect
        {
            Texture = GetIcon(icon),
            MinSize = new Vector2(ValueColumnWidth, 20),
            Stretch = TextureRect.StretchMode.KeepAspectCentered,
            VerticalAlignment = VAlignment.Center,
            ToolTip = Loc.GetString(tooltip),
            ModulateSelfOverride = LabelColor,
        });
    }

    private void UpdateHardware(Entity<ModSuitComponent> suit)
    {
        var partEntities = suit.Comp.PartEntities;
        var keys = partEntities.Keys.ToList();

        if (!_hardwareBuilt || !keys.SequenceEqual(_partRows.Keys))
        {
            _hardwareBuilt = true;
            HardwareList.RemoveAllChildren();
            _partRows.Clear();

            _controlValue = AddLabeledRow(HardwareList, Loc.GetString("modsuit-ui-control-unit"));
            _coreValue = AddLabeledRow(HardwareList, Loc.GetString("modsuit-ui-core-label"));

            foreach (var slot in keys)
            {
                var row = new BoxContainer
                {
                    Orientation = BoxContainer.LayoutOrientation.Horizontal,
                    HorizontalExpand = true,
                    SeparationOverride = 4,
                };

                row.AddChild(new Label
                {
                    Text = Loc.GetString("modsuit-ui-part-slot", ("part", PartName(slot))),
                    MinWidth = LabelColumnWidth,
                    ClipText = true,
                    VerticalAlignment = VAlignment.Center,
                    FontColorOverride = LabelColor,
                });

                var value = new Label
                {
                    HorizontalExpand = true,
                    ClipText = true,
                    VerticalAlignment = VAlignment.Center,
                };
                row.AddChild(value);

                var button = new ModSuitIconButton { MinWidth = 70 };
                SetButtonIcon(button, "arrow-up");
                button.OnPressed += _ => OnTogglePart?.Invoke(slot);
                StyleButton(button);
                row.AddChild(button);

                HardwareList.AddChild(row);
                _partRows[slot] = (button, value);
            }

            _aiValue = AddLabeledRow(HardwareList, Loc.GetString("modsuit-ui-ai-assistant"));
        }

        _controlValue!.Text = _entMan.GetComponent<MetaDataComponent>(suit).EntityName;
        _coreValue!.Text = _modSuit.GetCore(suit) is { } core
            ? _entMan.GetComponent<MetaDataComponent>(core).EntityName
            : Loc.GetString("modsuit-ui-no-core-detected");

        foreach (var (slot, (button, value)) in _partRows)
        {
            if (!partEntities.TryGetValue(slot, out var part))
                continue;

            value.Text = _entMan.GetComponent<MetaDataComponent>(part).EntityName;
            var deployed = _modSuit.IsPartDeployed(suit, slot);
            SetButtonIcon(button, deployed ? "arrow-down" : "arrow-up");
            button.Text = Loc.GetString(deployed ? "modsuit-ui-retract" : "modsuit-ui-deploy");
            StyleButton(button, deployed ? GoodColor : PrimaryColor);
        }

        _aiValue!.Text = Loc.GetString("modsuit-ui-no-ai");
    }

    private Label AddLabeledRow(BoxContainer parent, string labelText)
    {
        var row = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            SeparationOverride = 4,
        };

        row.AddChild(new Label
        {
            Text = labelText,
            MinWidth = LabelColumnWidth,
            ClipText = true,
            VerticalAlignment = VAlignment.Center,
            FontColorOverride = LabelColor,
        });

        var value = new Label
        {
            HorizontalExpand = true,
            ClipText = true,
            VerticalAlignment = VAlignment.Center,
        };
        row.AddChild(value);
        parent.AddChild(row);
        return value;
    }

    private Texture? GetIcon(string state)
    {
        if (_iconRsi != null && _iconRsi.TryGetState(state, out var rsiState))
            return rsiState.Frame0;

        return null;
    }

    private void SetButtonIcon(ModSuitIconButton button, string state)
    {
        button.IconTexture = GetIcon(state);
    }

    private static Label MakeValueLabel()
    {
        return new Label
        {
            MinWidth = ValueColumnWidth,
            HorizontalAlignment = HAlignment.Center,
            VerticalAlignment = VAlignment.Center,
            ClipText = true,
        };
    }

    private static void StyleButton(Button button, Color? background = null)
    {
        var color = background ?? PrimaryColor;
        var box = new StyleBoxFlat
        {
            BackgroundColor = color,
            BorderColor = color,
            BorderThickness = new Thickness(1),
        };
        box.SetContentMarginOverride(StyleBox.Margin.Horizontal, 4);
        box.SetContentMarginOverride(StyleBox.Margin.Vertical, 1);

        button.StyleBoxOverride = box;
        button.Label.FontColorOverride = Color.White;
        button.MinHeight = 20;
    }

    private static string PartName(string slot)
    {
        return slot switch
        {
            "head" => Loc.GetString("modsuit-ui-part-head"),
            "outerClothing" => Loc.GetString("modsuit-ui-part-outerclothing"),
            "gloves" => Loc.GetString("modsuit-ui-part-gloves"),
            "shoes" => Loc.GetString("modsuit-ui-part-shoes"),
            _ => slot,
        };
    }

    private sealed record ModuleRow(
        BoxContainer Root,
        ModSuitIconButton Select,
        ModSuitIconButton Eject,
        ModSuitIconButton Pin,
        CollapsibleHeading Heading,
        Label Idle,
        Label ActivePower,
        Label Use,
        Label Complexity);
}
