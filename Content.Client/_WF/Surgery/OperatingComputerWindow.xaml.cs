using System.Numerics;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._WF.Surgery;

[GenerateTypedNameReferences]
public sealed partial class OperatingComputerWindow : BaseWindow
{
    public OperatingComputerWindow()
    {
        RobustXamlLoader.Load(this);
        MouseFilter = MouseFilterMode.Stop;
        CloseButton.OnPressed += _ => Close();
    }

    protected override DragMode GetDragModeFor(Vector2 relativeMousePos)
    {
        // The whole title bar drags the window, like DefaultWindow's header.
        if (relativeMousePos.Y <= 25f)
            return DragMode.Move;

        return base.GetDragModeFor(relativeMousePos);
    }
}
