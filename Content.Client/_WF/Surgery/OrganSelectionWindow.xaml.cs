using System;
using System.Collections.Generic;
using System.Numerics;
using Content.Shared._WF.Surgery;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.GameObjects;

namespace Content.Client._WF.Surgery;

/// <summary>The organ list opened by the generic organ-manipulation operation.</summary>
[GenerateTypedNameReferences]
public sealed partial class OrganSelectionWindow : DefaultWindow
{
    private readonly List<(Button Button, SurgicalOrganOption Option)> _options = new();
    private SurgicalOrganOption? _selected;
    private bool _chosen;

    public event Action<NetEntity?, bool>? OnChosen;
    public event Action? OnCancelled;

    public OrganSelectionWindow()
    {
        RobustXamlLoader.Load(this);

        ConfirmButton.Disabled = true;
        ConfirmButton.OnPressed += _ => Confirm();
        CancelButton.OnPressed += _ => Close();
        OnClose += () =>
        {
            if (!_chosen)
                OnCancelled?.Invoke();
        };
    }

    /// <summary>Fills the list; a single organ is preselected so Enter-like confirmation still works.</summary>
    public void SetOptions(SurgicalOrganSelectState state)
    {
        Options.DisposeAllChildren();
        _options.Clear();
        _selected = null;
        _chosen = false;
        ConfirmButton.Disabled = true;

        foreach (var option in state.Options)
        {
            var button = new Button
            {
                Text = option.Name,
                ToggleMode = true,
                HorizontalExpand = true,
                MinSize = new Vector2(0, 26),
            };

            var captured = option;
            button.OnToggled += args =>
            {
                if (!args.Pressed)
                {
                    if (ReferenceEquals(_selected, captured))
                    {
                        _selected = null;
                        ConfirmButton.Disabled = true;
                    }

                    return;
                }

                _selected = captured;
                foreach (var (other, _) in _options)
                {
                    if (other != button)
                        other.Pressed = false;
                }

                ConfirmButton.Disabled = false;
            };

            _options.Add((button, option));
            Options.AddChild(button);
        }

        if (_options.Count == 1)
        {
            _options[0].Button.Pressed = true;
            _selected = _options[0].Option;
            ConfirmButton.Disabled = false;
        }
    }

    private void Confirm()
    {
        if (_selected is not { } selected)
            return;

        _chosen = true;
        OnChosen?.Invoke(selected.Organ, selected.Inserting);
        Close();
    }
}
