/// <summary>
/// Card-based trait editor: search, sorting, collapsible categories with subgroups, and inline requirements.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class TraitsTab : BoxContainer
{
    [Dependency] private IPrototypeManager _prototype = default!;
    [Dependency] private IConfigurationManager _cfg = default!;
    [Dependency] private JobRequirementsManager _requirements = default!;
    [Dependency] private IComponentFactory _componentFactory = default!;
    [Dependency] private ILocalizationManager _loc = default!;

    /// <summary>Raised when the editor changes the profile's trait selection.</summary>
    public event Action<HumanoidCharacterProfile>? OnProfileChanged;

    /// <summary>The editor's current profile, read before each change so other edits are kept.</summary>
    public Func<HumanoidCharacterProfile?>? ProfileSource;

    private readonly List<TraitCategory> _categories = new();
    private readonly Dictionary<ProtoId<TraitPrototype>, TraitEntry> _entries = new();
    private readonly HashSet<ProtoId<TraitPrototype>> _selected = new();
    private readonly Dictionary<string, HashSet<string>> _conflicts = new();

    private static readonly LocId[] SortNames =
    {
        "trait-editor-sort-name",
        "trait-editor-sort-cost-high",
        "trait-editor-sort-cost-low",
    };

    private const string BlockedColor = "#ff5555";
    private const string InfoColor = "#8a94a3";

    private HumanoidCharacterProfile? _profile;
    private bool _updating;
    private bool _pendingRebuild = true;
    private bool _resetScroll;
    private string _search = string.Empty;
    private TraitSortMode _sort = TraitSortMode.Name;
    private bool _hideUnavailable;

    public TraitsTab()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        SearchBar.OnTextChanged += args =>
        {
            _search = args.Text.Trim();
            ApplySearch();
        };

        ClearButton.OnPressed += _ => ClearAll();

        for (var i = 0; i < SortNames.Length; i++)
            SortSelect.AddItem(Loc.GetString(SortNames[i]), i);

        SortSelect.OnItemSelected += args =>
        {
            SetSort((TraitSortMode) args.Id);
        };

        HideUnavailableCheck.OnToggled += args =>
        {
            _hideUnavailable = args.Pressed;
            ApplySearch();
        };
    }

    protected override void EnteredTree()
    {
        base.EnteredTree();

        if (_pendingRebuild)
            Rebuild();
    }

    protected override void VisibilityChanged(bool newVisible)
    {
        base.VisibilityChanged(newVisible);

        if (!newVisible)
            return;

        if (_pendingRebuild)
            Rebuild();
        else
        {
            // The editor is reused after it closes, so a stale measure would cram the rows together.
            InvalidateLayoutTree(this);
        }
    }

    private static void InvalidateLayoutTree(Control control)
    {
        control.InvalidateMeasure();
        control.InvalidateArrange();

        foreach (var child in control.Children)
            InvalidateLayoutTree(child);
    }

    private void SyncProfile()
    {
        _profile = ProfileSource?.Invoke() ?? _profile;
    }

    private void ClearAll()
    {
        SyncProfile();
        if (_profile == null)
            return;

        _profile = _profile.WithoutAllTraitPreferences();
        _selected.Clear();
        RefreshEntries();
        OnProfileChanged?.Invoke(_profile);
    }

    /// <summary>Rebuilds the editor from the current profile.</summary>
    public void SetProfile(HumanoidCharacterProfile? profile)
    {
        // Reopening the editor starts at the top of the list rather than the old scroll offset.
        if (_profile == null && profile != null)
            _resetScroll = true;

        _profile = profile;
        _pendingRebuild = true;

        if (!IsInsideTree || VisibleInTree)
            Rebuild();
    }

    private void Rebuild()
    {
        _pendingRebuild = false;
        _updating = true;
        CategoriesContainer.DisposeAllChildren();
        _categories.Clear();
        _entries.Clear();
        _selected.Clear();

        if (_profile == null)
        {
            SelectionLabel.Text = string.Empty;
            _updating = false;
            InvalidateMeasure();
            InvalidateArrange();
            return;
        }

        _selected.UnionWith(_profile.TraitPreferences);

        var groups = new Dictionary<string, List<TraitPrototype>>();
        foreach (var trait in _prototype.EnumeratePrototypes<TraitPrototype>().OrderBy(t => Loc.GetString(t.Name)))
        {
            var categoryId = trait.Category ?? TraitCategoryPrototype.Default;
            if (trait.Category != null && !_prototype.HasIndex<TraitCategoryPrototype>(categoryId))
                continue;

            if (!groups.TryGetValue(categoryId, out var list))
            {
                list = new List<TraitPrototype>();
                groups[categoryId] = list;
            }

            list.Add(trait);
        }

        BuildConflicts();

        foreach (var category in _prototype.EnumeratePrototypes<TraitCategoryPrototype>()
                     .OrderBy(c => _prototype.TryIndex<WFTraitLayoutPrototype>(c.ID, out var layout)
                         ? layout.Priority
                         : int.MaxValue)
                     .ThenBy(c => Loc.GetString(c.Name)))
        {
            if (groups.TryGetValue(category.ID, out var traits))
                AddCategory(category.ID, category, traits);
        }

        if (groups.TryGetValue(TraitCategoryPrototype.Default, out var defaultTraits))
            AddCategory(TraitCategoryPrototype.Default, null, defaultTraits);

        _updating = false;
        ApplySort();
        RefreshEntries();
        InvalidateLayoutTree(this);

        if (_resetScroll)
        {
            TraitScroll.VScroll = 0;
            TraitScroll.VScrollTarget = 0;
            _resetScroll = false;
        }
    }

    private void AddCategory(string id, TraitCategoryPrototype? prototype, IEnumerable<TraitPrototype> traits)
    {
        _prototype.TryIndex<WFTraitLayoutPrototype>(id, out var layout);
        var category = new TraitCategory(id, prototype, layout, traits);
        foreach (var entry in category.Entries)
        {
            entry.Toggled += OnEntryToggled;
            _entries[entry.Trait.ID] = entry;
        }

        _categories.Add(category);
        CategoriesContainer.AddChild(category);
    }

    /// <summary>Collects mutual exclusions in both directions, since a trait may only name the other one.</summary>
    private void BuildConflicts()
    {
        _conflicts.Clear();
        foreach (var trait in _prototype.EnumeratePrototypes<TraitPrototype>())
        {
            foreach (var other in trait.MutuallyExclusiveTraits)
            {
                if (other == trait.ID || !_prototype.HasIndex(other))
                    continue;

                AddConflict(trait.ID, other);
                AddConflict(other, trait.ID);
            }
        }
    }

    private void AddConflict(string a, string b)
    {
        if (!_conflicts.TryGetValue(a, out var set))
        {
            set = new HashSet<string>();
            _conflicts[a] = set;
        }

        set.Add(b);
    }

    /// <summary>Changes how traits are ordered inside each subgroup.</summary>
    public void SetSort(TraitSortMode mode)
    {
        _sort = mode;
        SortSelect.SelectId((int) mode);
        ApplySort();
    }

    private void ApplySort()
    {
        Comparison<TraitEntry> comparison = _sort switch
        {
            TraitSortMode.CostHigh => (a, b) => CompareThenName(b.Trait.Cost.CompareTo(a.Trait.Cost), a, b),
            TraitSortMode.CostLow => (a, b) => CompareThenName(a.Trait.Cost.CompareTo(b.Trait.Cost), a, b),
            _ => (a, b) => CompareThenName(0, a, b),
        };

        foreach (var category in _categories)
            category.Sort(comparison);
    }

    private static int CompareThenName(int result, TraitEntry a, TraitEntry b)
    {
        return result != 0
            ? result
            : string.Compare(Loc.GetString(a.Trait.Name), Loc.GetString(b.Trait.Name),
                StringComparison.CurrentCultureIgnoreCase);
    }

    private void RefreshEntries()
    {
        if (_profile == null)
            return;

        var points = new Dictionary<string, int>();
        var counts = new Dictionary<string, int>();

        foreach (var id in _selected)
        {
            if (!_prototype.TryIndex(id, out var trait))
                continue;

            var categoryId = trait.Category ?? TraitCategoryPrototype.Default;
            points[categoryId] = points.GetValueOrDefault(categoryId) + trait.Cost;
            counts[categoryId] = counts.GetValueOrDefault(categoryId) + 1;
        }

        foreach (var category in _categories)
        {
            var used = points.GetValueOrDefault(category.CategoryId);
            var count = counts.GetValueOrDefault(category.CategoryId);
            var max = category.Prototype?.MaxTraitPoints;

            foreach (var entry in category.Entries)
            {
                var trait = entry.Trait;
                var selected = _selected.Contains(trait.ID);
                var overLimit = !selected && max is >= 0 && used + trait.Cost > max;
                var conditionsMet = TraitConditionUi.AllMet(trait, _profile.Species.Id, _prototype);
                var (restrictionNotes, blocked) = EvaluateRestrictions(trait);
                var disabled = !selected && (!conditionsMet || blocked || overLimit);

                entry.SetSelected(selected);
                entry.SetDisabled(disabled);
                entry.Unavailable = disabled;
                entry.SetTooltip(BuildTooltip(trait, conditionsMet, restrictionNotes, overLimit));
                entry.SetNotes(BuildNotes(trait, overLimit));
            }

            category.UpdateStats(count, used, max);
        }

        SelectionLabel.Text = Loc.GetString("trait-editor-selected-count", ("count", _selected.Count));
        ApplySearch();
    }

    private (List<string> Notes, bool Blocked) EvaluateRestrictions(TraitPrototype trait)
    {
        var notes = new List<string>();
        var blocked = false;

        if (_profile == null)
            return (notes, false);

        if (trait.SpeciesBlacklist.Contains(_profile.Species))
        {
            var speciesNames = new List<string>();
            foreach (var speciesId in trait.SpeciesBlacklist)
            {
                if (_prototype.TryIndex(speciesId, out var species))
                    speciesNames.Add(Loc.GetString(species.Name));
            }

            notes.Add(Loc.GetString("trait-reason-species-blacklist",
                ("species", string.Join(", ", speciesNames))));
            blocked = true;
        }

        if (WFBiotypeGates.TraitBlocked(trait, _profile, _prototype))
        {
            var biotypeNames = trait.BiotypeBlacklist
                .Select(biotype => Loc.GetString($"wf-biotype-{biotype.ToString().ToLowerInvariant()}"))
                .ToList();

            notes.Add(Loc.GetString("wf-biotype-trait-blocked", ("biotypes", string.Join(", ", biotypeNames))));
            blocked = true;
        }

        // The server decides whether this player has the newbie tag, so the warning stays visible for everyone.
        if (trait.NewbieBlocked)
        {
            notes.Add(Loc.GetString("wf-newbie-trait-blocked"));

            if (WFNewbieTraitRules.TraitBlocked(trait, _cfg, _requirements))
                blocked = true;
        }

        var conflicts = new List<string>();
        foreach (var selectedId in _selected)
        {
            if (selectedId == trait.ID)
                continue;

            if (trait.MutuallyExclusiveTraits.Contains(selectedId))
            {
                if (_prototype.TryIndex(selectedId, out var selectedTrait))
                    conflicts.Add(Loc.GetString(selectedTrait.Name));
            }
            else if (_prototype.TryIndex(selectedId, out var selectedTrait) &&
                     selectedTrait.MutuallyExclusiveTraits.Contains(trait.ID))
            {
                conflicts.Add(Loc.GetString(selectedTrait.Name));
            }
        }

        if (conflicts.Count > 0)
        {
            notes.Add(Loc.GetString("trait-reason-conflict", ("traits", string.Join(", ", conflicts))));
            blocked = true;
        }

        AddWhitelistNotes(trait.Whitelist, true, notes, ref blocked);
        AddWhitelistNotes(trait.Blacklist, false, notes, ref blocked);

        return (notes, blocked);
    }

    private void AddWhitelistNotes(EntityWhitelist? list, bool isWhitelist, List<string> notes, ref bool blocked)
    {
        if (list == null || list.Components is not { Length: > 0 } && list.Tags is not { Count: > 0 })
            return;

        var label = FormatWhitelist(list);
        var entityProto = SpeciesEntityPrototype();

        // A server-only component is missing from the client's prototypes, so it can't count against the body.
        var serverOnly = list.Components?.Any(name => !_componentFactory.TryGetRegistration(name, out _)) == true;
        if (entityProto == null || serverOnly)
        {
            // The editor cannot check the species body, so show what the trait expects without blocking it.
            notes.Add(Loc.GetString(isWhitelist ? "trait-reason-whitelist" : "trait-reason-blacklist",
                ("components", label)));
            return;
        }

        var matches = MatchesWhitelist(entityProto, list);
        if (isWhitelist ? matches : !matches)
            return;

        notes.Add(Loc.GetString(isWhitelist ? "trait-reason-whitelist" : "trait-reason-blacklist",
            ("components", label)));
        blocked = true;
    }

    private bool MatchesWhitelist(EntityPrototype entity, EntityWhitelist list)
    {
        var checks = new List<bool>();

        if (list.Components != null)
        {
            foreach (var component in list.Components)
                checks.Add(entity.Components.ContainsKey(component));
        }

        if (list.Tags is { Count: > 0 })
        {
            HashSet<ProtoId<TagPrototype>>? tags = null;
            if (entity.TryGetComponent<TagComponent>(out var tagComponent))
                tags = tagComponent.Tags;

            foreach (var tag in list.Tags)
                checks.Add(tags?.Contains(tag) == true);
        }

        if (checks.Count == 0)
            return true;

        return list.RequireAll ? checks.All(check => check) : checks.Any(check => check);
    }

    private EntityPrototype? SpeciesEntityPrototype()
    {
        if (_profile == null ||
            !_prototype.TryIndex<SpeciesPrototype>(_profile.Species, out var species) ||
            !_prototype.TryIndex<EntityPrototype>(species.Prototype.Id, out var entity))
        {
            return null;
        }

        return entity;
    }

    private static string FormatWhitelist(EntityWhitelist list)
    {
        var parts = new List<string>();
        if (list.Components != null)
            parts.AddRange(list.Components);
        if (list.Tags != null)
            parts.AddRange(list.Tags.Select(tag => tag.Id));

        return string.Join(", ", parts);
    }

    /// <summary>
    /// Inline lines under a trait: every requirement and incompatibility, red where it blocks this character.
    /// </summary>
    private List<string> BuildNotes(TraitPrototype trait, bool overLimit)
    {
        var lines = new List<string>();
        if (_profile == null)
            return lines;

        var ctx = new TraitConditionContext { SpeciesId = _profile.Species.Id, Proto = _prototype };
        foreach (var condition in trait.Conditions)
        {
            var text = condition.GetTooltip(_prototype, _loc);
            if (!string.IsNullOrEmpty(text))
                lines.Add(Note(text, !condition.Evaluate(ctx)));
        }

        if (trait.SpeciesBlacklist.Count > 0)
        {
            var names = trait.SpeciesBlacklist
                .Select(id => _prototype.TryIndex(id, out var species) ? Loc.GetString(species.Name) : id.Id);
            lines.Add(Note(Loc.GetString("trait-reason-species-blacklist", ("species", string.Join(", ", names))),
                trait.SpeciesBlacklist.Contains(_profile.Species)));
        }

        if (trait.BiotypeBlacklist.Count > 0)
        {
            var names = trait.BiotypeBlacklist
                .Select(biotype => Loc.GetString($"wf-biotype-{biotype.ToString().ToLowerInvariant()}"));
            lines.Add(Note(Loc.GetString("wf-biotype-trait-blocked", ("biotypes", string.Join(", ", names))),
                WFBiotypeGates.TraitBlocked(trait, _profile, _prototype)));
        }

        if (_conflicts.TryGetValue(trait.ID, out var conflicts))
        {
            var names = conflicts
                .Select(id => (Name: Loc.GetString(_prototype.Index<TraitPrototype>(id).Name),
                    Selected: _selected.Contains(id)))
                .OrderBy(c => c.Name)
                .Select(c => c.Selected
                    ? Loc.GetString("trait-editor-incompatible-selected", ("trait", c.Name))
                    : c.Name);
            lines.Add(Note(Loc.GetString("trait-editor-incompatible", ("traits", string.Join(", ", names))),
                false));
        }

        if (trait.NewbieBlocked)
            lines.Add(Loc.GetString("wf-newbie-trait-blocked"));

        AddBodyNote(trait.Whitelist, true, lines);
        AddBodyNote(trait.Blacklist, false, lines);

        if (overLimit)
            lines.Add(Note(Loc.GetString("trait-editor-not-enough-points"), true));

        return lines;
    }

    private void AddBodyNote(EntityWhitelist? list, bool isWhitelist, List<string> lines)
    {
        var notes = new List<string>();
        var blocked = false;
        AddWhitelistNotes(list, isWhitelist, notes, ref blocked);
        foreach (var note in notes)
            lines.Add(Note(note, blocked));
    }

    private static string Note(string text, bool blocking)
    {
        return $"[color={(blocking ? BlockedColor : InfoColor)}]{(blocking ? "✗" : "•")} {text}[/color]";
    }

    private string? BuildTooltip(TraitPrototype trait, bool conditionsMet, List<string> restrictionNotes,
        bool overLimit)
    {
        var parts = new List<string>();
        if (trait.Description is { } description)
            parts.Add(Loc.GetString(description));

        if (trait.Conditions.Count > 0)
        {
            var before = parts.Count;
            parts.Add(Loc.GetString(conditionsMet
                ? "trait-condition-header"
                : "trait-condition-unmet-header"));

            TraitConditionUi.AddTooltipLines(trait, _prototype, parts,
                onlyUnmet: !conditionsMet, speciesId: _profile?.Species.Id);

            if (parts.Count == before + 1)
                parts.RemoveAt(parts.Count - 1);
        }

        parts.AddRange(restrictionNotes);

        if (overLimit)
            parts.Add(Loc.GetString("trait-editor-not-enough-points"));

        return parts.Count == 0 ? null : string.Join("\n", parts);
    }

    private int PointsIn(string categoryId)
    {
        var points = 0;
        foreach (var id in _selected)
        {
            if (_prototype.TryIndex(id, out var trait) &&
                (trait.Category ?? TraitCategoryPrototype.Default) == categoryId)
                points += trait.Cost;
        }

        return points;
    }

    private void OnEntryToggled(TraitEntry entry, bool pressed)
    {
        if (_updating)
            return;

        SyncProfile();
        if (_profile == null)
            return;

        var trait = entry.Trait;
        var selected = _selected.Contains(trait.ID);
        if (pressed == selected)
            return;

        if (pressed)
        {
            var (_, blocked) = EvaluateRestrictions(trait);
            if (!TraitConditionUi.AllMet(trait, _profile.Species.Id, _prototype) || blocked)
            {
                entry.SetSelected(false);
                return;
            }

            var categoryId = trait.Category ?? TraitCategoryPrototype.Default;
            var max = trait.Category != null &&
                      _prototype.TryIndex(trait.Category, out var category)
                ? category.MaxTraitPoints
                : null;

            if (max is >= 0 && PointsIn(categoryId) + trait.Cost > max)
            {
                entry.SetSelected(false);
                return;
            }

            var updated = _profile.WithTraitPreference(trait.ID, _prototype);
            if (!updated.TraitPreferences.Contains(trait.ID))
            {
                entry.SetSelected(false);
                return;
            }

            _profile = updated;
        }
        else
        {
            _profile = _profile.WithoutTraitPreference(trait.ID, _prototype);
        }

        _selected.Clear();
        _selected.UnionWith(_profile.TraitPreferences);

        RefreshEntries();
        OnProfileChanged?.Invoke(_profile);
    }

    private void ApplySearch()
    {
        if (_profile == null)
            return;

        foreach (var category in _categories)
        {
            foreach (var entry in category.Entries)
            {
                var matches = string.IsNullOrEmpty(_search) ||
                              Loc.GetString(entry.Trait.Name).Contains(_search, StringComparison.OrdinalIgnoreCase) ||
                              (entry.Trait.Description is { } description &&
                               Loc.GetString(description).Contains(_search, StringComparison.OrdinalIgnoreCase));

                entry.Visible = matches && !(_hideUnavailable && entry.Unavailable);
            }

            category.Visible = category.UpdateGroupVisibility();
        }
    }
}

/// <summary>Trait order inside each subgroup.</summary>
public enum TraitSortMode
{
    Name,
    CostHigh,
    CostLow,
}
