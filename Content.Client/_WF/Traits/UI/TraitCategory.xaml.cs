using System.Linq;
using Content.Shared._WF.Traits;
using Content.Shared.Traits;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._WF.Traits.UI;

/// <summary>
/// A collapsible trait category, split into the subgroups its layout prototype names.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class TraitCategory : PanelContainer
{
    [Dependency] private ILocalizationManager _loc = default!;

    public string CategoryId { get; }

    public TraitCategoryPrototype? Prototype { get; }

    public IReadOnlyList<TraitEntry> Entries => _entries;

    private readonly List<TraitEntry> _entries = new();
    private readonly List<(Label Header, BoxContainer Box, List<TraitEntry> Entries)> _groups = new();
    private bool _expanded = true;

    public TraitCategory(string categoryId, TraitCategoryPrototype? prototype, WFTraitLayoutPrototype? layout,
        IEnumerable<TraitPrototype> traits)
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        CategoryId = categoryId;
        Prototype = prototype;
        CategoryNameLabel.Text = layout?.Name is { } layoutName
            ? _loc.GetString(layoutName)
            : prototype == null
                ? _loc.GetString("humanoid-profile-editor-traits-default-category")
                : _loc.GetString(prototype.Name);

        HeaderButton.OnPressed += _ => SetExpanded(!_expanded);

        var remaining = traits.ToList();
        var hasGroups = layout is { Groups.Count: > 0 };

        if (hasGroups)
        {
            foreach (var group in layout!.Groups)
            {
                var members = remaining.Where(t => group.Traits.Contains(t.ID)).ToList();
                remaining.RemoveAll(members.Contains);
                AddGroup(_loc.GetString(group.Name), members);
            }
        }

        AddGroup(hasGroups ? _loc.GetString("trait-editor-group-other") : null, remaining);

        SetExpanded(true);
        UpdateStats(0, 0);
    }

    private void AddGroup(string? title, List<TraitPrototype> traits)
    {
        if (traits.Count == 0)
            return;

        var header = new Label
        {
            Text = title ?? string.Empty,
            StyleClasses = { "CreatorFieldLabel" },
            Visible = title != null,
            Margin = new Thickness(2, 6, 0, 2),
            ModulateSelfOverride = Color.FromHex("#a8b4c4"),
        };

        var box = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
            SeparationOverride = 4,
        };

        var entries = new List<TraitEntry>();
        foreach (var trait in traits)
        {
            var entry = new TraitEntry(trait);
            entries.Add(entry);
            _entries.Add(entry);
            box.AddChild(entry);
        }

        TraitsContainer.AddChild(header);
        TraitsContainer.AddChild(box);
        _groups.Add((header, box, entries));
    }

    /// <summary>Reorders the traits inside each subgroup.</summary>
    public void Sort(Comparison<TraitEntry> comparison)
    {
        foreach (var (_, _, entries) in _groups)
        {
            entries.Sort(comparison);
            for (var i = 0; i < entries.Count; i++)
                entries[i].SetPositionInParent(i);
        }
    }

    /// <summary>Hides subgroup headers with no visible traits and returns whether any trait is visible.</summary>
    public bool UpdateGroupVisibility()
    {
        var anyVisible = false;
        foreach (var (header, box, entries) in _groups)
        {
            var visible = entries.Any(e => e.Visible);
            box.Visible = visible;
            header.Visible = visible && !string.IsNullOrEmpty(header.Text);
            anyVisible |= visible;
        }

        return anyVisible;
    }

    public void SetExpanded(bool expanded)
    {
        _expanded = expanded;
        TraitsContainer.Visible = expanded;
        ExpandIcon.Text = expanded ? "▾" : "▸";
        InvalidateMeasure();
        InvalidateArrange();
    }

    public void UpdateStats(int selected, int points, int? maxPoints = null)
    {
        if (maxPoints is >= 0)
        {
            CategoryStatsLabel.Text = _loc.GetString("trait-editor-category-stats",
                ("selected", selected), ("points", points), ("max", maxPoints.Value));
            return;
        }

        CategoryStatsLabel.Text = _loc.GetString("trait-editor-category-selected",
            ("selected", selected));
    }
}
