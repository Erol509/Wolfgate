using Content.Shared._WF.TestDummies;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._WF.TestDummies;

/// <summary>The admin's test dummy window: what to ask, who to ask, and who said what.</summary>
[GenerateTypedNameReferences]
public sealed partial class WFTestDummyWindow : DefaultWindow
{
    /// <summary>Send the filled-in request.</summary>
    public event Action<WFTestDummyRequest>? OnSend;

    /// <summary>End the current call.</summary>
    public event Action? OnEnd;

    private static readonly Color OptedInColor = Color.FromHex("#6fd36f");
    private static readonly Color OptedOutColor = Color.FromHex("#e06c6c");
    private static readonly Color PendingColor = Color.FromHex("#a0a0a0");

    public WFTestDummyWindow()
    {
        RobustXamlLoader.Load(this);

        DurationSpin.IsValid = v => v >= 0 && v <= (int) WFTestDummyLimits.MaxDuration;
        DurationSpin.Value = 120;
        DurationSpin.InitDefaultButtons();

        SendButton.OnPressed += _ => OnSend?.Invoke(Build());
        EndButton.OnPressed += _ => OnEnd?.Invoke();
    }

    private WFTestDummyRequest Build()
    {
        var audience = WFTestDummyAudience.None;
        if (OwnsShipCheck.Pressed)
            audience |= WFTestDummyAudience.OwnsShip;
        if (InSpaceCheck.Pressed)
            audience |= WFTestDummyAudience.InSpace;
        if (InBodyCheck.Pressed)
            audience |= WFTestDummyAudience.InBody;
        if (SkipAdminsCheck.Pressed)
            audience |= WFTestDummyAudience.SkipAdmins;

        return new WFTestDummyRequest
        {
            Description = DescriptionEdit.Text.Trim(),
            Audience = audience,
            Duration = DurationSpin.Value,
        };
    }

    /// <summary>Redraws the list and the status line from the server's state.</summary>
    public void Update(WFTestDummyEuiState state)
    {
        EndButton.Disabled = !state.Active;

        if (state.Status != null)
        {
            StatusLabel.Text = state.Status;
            StatusLabel.FontColorOverride = state.Error ? OptedOutColor : null;
        }

        var optedIn = 0;
        var optedOut = 0;
        var pending = 0;
        foreach (var entry in state.Entries)
        {
            switch (entry.Answer)
            {
                case WFTestDummyAnswer.OptedIn:
                    optedIn++;
                    break;
                case WFTestDummyAnswer.OptedOut:
                    optedOut++;
                    break;
                default:
                    pending++;
                    break;
            }
        }

        SummaryLabel.Text = state.Entries.Count == 0
            ? Loc.GetString("wf-test-dummy-list-empty")
            : Loc.GetString("wf-test-dummy-summary", ("in", optedIn), ("out", optedOut), ("pending", pending),
                ("active", state.Active));

        EntryList.RemoveAllChildren();
        foreach (var entry in state.Entries)
        {
            EntryList.AddChild(Row(entry));
        }
    }

    private static Control Row(WFTestDummyEntry entry)
    {
        var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 8 };

        var answer = new Label
        {
            Text = Loc.GetString(WFTestDummyFormat.AnswerKey(entry.Answer)),
            MinWidth = 90,
            FontColorOverride = entry.Answer switch
            {
                WFTestDummyAnswer.OptedIn => OptedInColor,
                WFTestDummyAnswer.OptedOut => OptedOutColor,
                _ => PendingColor,
            },
        };
        row.AddChild(answer);

        var who = new Label
        {
            Text = WFTestDummyFormat.Describe(entry),
            HorizontalExpand = true,
            ClipText = true,
        };
        if (!entry.Connected)
            who.FontColorOverride = PendingColor;
        row.AddChild(who);

        return row;
    }
}
