using Content.Shared._WF.Administration.SecondChance;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._WF.Administration.UI.SecondChance;

/// <summary>
/// Asks the player whether they want to go back into their body, healed. Closing it counts as a no.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class SecondChancePromptWindow : DefaultWindow
{
    /// <summary>Raised once, with whether the player said yes.</summary>
    public event Action<bool>? Answered;

    public readonly int OfferId;

    private bool _answered;

    public SecondChancePromptWindow(SecondChanceOfferEvent ev)
    {
        RobustXamlLoader.Load(this);
        OfferId = ev.OfferId;

        // Names are player-controlled text, so they must not be parsed as markup.
        MessageLabel.SetMessage(FormattedMessage.FromMarkupOrThrow(Loc.GetString("wf-second-chance-prompt-message",
            ("name", FormattedMessage.EscapeText(ev.BodyName)))));

        YesButton.OnPressed += _ =>
        {
            Answer(true);
            Close();
        };
        NoButton.OnPressed += _ => Close();
        OnClose += () => Answer(false);
    }

    private void Answer(bool accepted)
    {
        if (_answered)
            return;

        _answered = true;
        Answered?.Invoke(accepted);
    }
}
