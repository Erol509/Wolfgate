using System.Globalization;
using Content.Client.Message;
using Content.Shared._WF.Defcon;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._WF.Defcon;

/// <summary>The DEFCON admin panel: the level, set or lock it, bias the score and see what makes it up.</summary>
[GenerateTypedNameReferences]
public sealed partial class WFDefconWindow : DefaultWindow
{
    /// <summary>Raised with the level, whether to lock it and whether to announce it.</summary>
    public event Action<int, bool, bool>? OnSetLevel;
    public event Action? OnUnlock;
    public event Action<float>? OnBias;
    public event Action? OnEvaluate;

    private bool _biasEdited;
    private bool _lockEdited;
    private bool _hasState;
    private int? _lastLocked;

    public WFDefconWindow()
    {
        RobustXamlLoader.Load(this);

        UnlockButton.OnPressed += _ => OnUnlock?.Invoke();
        EvaluateButton.OnPressed += _ => OnEvaluate?.Invoke();
        BiasEdit.OnTextChanged += _ => _biasEdited = true;
        BiasEdit.OnTextEntered += _ => SendBias();
        BiasButton.OnPressed += _ => SendBias();
        LockCheck.OnToggled += _ => _lockEdited = true;
    }

    private void SendBias()
    {
        if (!float.TryParse(BiasEdit.Text, NumberStyles.Float, CultureInfo.InvariantCulture, out var bias) || !float.IsFinite(bias))
            return;

        _biasEdited = false;
        OnBias?.Invoke(bias);
    }

    public void UpdateState(WFDefconEuiState state)
    {
        var current = state.Levels.Find(l => l.Level == state.Level);
        LevelLabel.SetMarkup(Loc.GetString("wf-defcon-panel-level",
            ("level", state.Level),
            ("name", current?.Name ?? state.Level.ToString()),
            ("color", (current?.Color ?? Color.White).ToHex())));

        StatusLabel.Text = state.Enabled
            ? Loc.GetString("wf-defcon-panel-status",
                ("score", state.Score.ToString("0.#", CultureInfo.InvariantCulture)),
                ("floor", state.Floor),
                ("locked", state.Locked != null ? "true" : "false"))
            : Loc.GetString("wf-defcon-panel-disabled");

        UnlockButton.Disabled = state.Locked == null;
        if (!_biasEdited)
            BiasEdit.Text = state.Bias.ToString("R", CultureInfo.InvariantCulture);

        // Follow the server's lock unless the admin has changed the box since it last moved.
        if (!_hasState || state.Locked != _lastLocked)
            _lockEdited = false;
        if (!_lockEdited)
            LockCheck.Pressed = state.Locked != null;
        _lastLocked = state.Locked;
        _hasState = true;

        LevelButtons.RemoveAllChildren();
        foreach (var level in state.Levels)
        {
            var button = new Button
            {
                Text = Loc.GetString("wf-defcon-panel-level-button", ("level", level.Level)),
                ToolTip = level.Name,
                HorizontalExpand = true,
                ModulateSelfOverride = level.Color,
                Pressed = level.Level == state.Level,
                ToggleMode = true,
            };
            var number = level.Level;
            button.OnPressed += _ =>
            {
                _lockEdited = false;
                OnSetLevel?.Invoke(number, LockCheck.Pressed, AnnounceCheck.Pressed);
            };
            LevelButtons.AddChild(button);
        }

        ReasonList.RemoveAllChildren();
        if (state.Reasons.Count == 0)
            ReasonList.AddChild(new Label { Text = Loc.GetString("wf-defcon-panel-no-threats"), StyleClasses = { "LabelSubText" } });

        foreach (var reason in state.Reasons)
        {
            ReasonList.AddChild(new Label
            {
                Text = Loc.GetString("wf-defcon-panel-reason",
                    ("score", reason.Score.ToString("0.#", CultureInfo.InvariantCulture)),
                    ("reason", reason.Reason)),
            });
        }
    }
}
