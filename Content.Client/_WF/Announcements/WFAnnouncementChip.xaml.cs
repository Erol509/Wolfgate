using Content.Shared._WF.Announcements;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Input;
using Robust.Shared.Utility;

namespace Content.Client._WF.Announcements;

/// <summary>
/// A TCAS-style notification strip: a coloured tag, the message and a countdown. Click to dismiss.
/// Ticked by <see cref="WFAnnouncementChipSystem"/> rather than FrameUpdate, so the window's preview can drive it too.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class WFAnnouncementChip : PanelContainer
{
    /// <summary>Flashes per second when flashing is on.</summary>
    private const float FlashRate = 2f;

    /// <summary>Seconds the chip fades out over at the end of its time.</summary>
    private const float FadeTime = 0.6f;

    private readonly StyleBoxFlat _background = new();
    private readonly StyleBoxFlat _tag = new();

    private bool _flash;
    private float _duration;
    private float _elapsed;

    /// <summary>Raised when the chip is clicked.</summary>
    public event Action<WFAnnouncementChip>? Dismissed;

    /// <summary>True once the chip has run its time.</summary>
    public bool Expired => _duration > 0f && _elapsed >= _duration;

    public WFAnnouncementChip()
    {
        RobustXamlLoader.Load(this);
        PanelOverride = _background;
        TagPanel.PanelOverride = _tag;
    }

    /// <summary>Fills the chip from an event and restarts its timer.</summary>
    public void Set(WFAnnouncementChipEvent chip)
    {
        var color = WFAnnounceFormat.ChipColor(chip.Level, chip.Accent);

        _background.BorderThickness = new Thickness(2);
        _background.BorderColor = color;
        _background.BackgroundColor = Color.Black.WithAlpha(0.75f);
        _tag.BackgroundColor = color;

        var title = chip.Title.Length > 0 ? chip.Title : Loc.GetString(LevelTag(chip.Level));
        TagLabel.Text = title.ToUpperInvariant();
        TagLabel.FontColorOverride = Color.Black;

        var text = new FormattedMessage();
        text.PushColor(color);
        text.AddText(chip.Text);
        text.Pop();
        TextLabel.SetMessage(text);

        SenderLabel.Text = chip.Sender;
        SenderLabel.Visible = chip.Sender.Length > 0;
        TimerLabel.FontColorOverride = color;

        _flash = chip.Flash;
        _duration = chip.Duration;
        _elapsed = 0f;
        Modulate = Color.White;
        UpdateTimer();
    }

    /// <summary>Advances the countdown, flash and fade.</summary>
    public void Tick(float frameTime)
    {
        _elapsed += frameTime;

        var alpha = 1f;
        if (_flash)
            alpha = MathF.Abs(MathF.Cos(_elapsed * FlashRate * MathF.PI)) * 0.5f + 0.5f;

        if (_duration > 0f)
            alpha *= Math.Clamp((_duration - _elapsed) / FadeTime, 0f, 1f);

        Modulate = Color.White.WithAlpha(alpha);
        UpdateTimer();
    }

    protected override void KeyBindDown(GUIBoundKeyEventArgs args)
    {
        base.KeyBindDown(args);

        if (args.Function != EngineKeyFunctions.UIClick)
            return;

        Dismissed?.Invoke(this);
        args.Handle();
    }

    private void UpdateTimer()
    {
        TimerLabel.Visible = _duration > 0f;
        TimerLabel.Text = Loc.GetString("wf-announce-chip-timer",
            ("seconds", MathF.Ceiling(MathF.Max(_duration - _elapsed, 0f))));
    }

    private static string LevelTag(WFAnnounceChipLevel level)
    {
        return level switch
        {
            WFAnnounceChipLevel.Info => "wf-announce-chip-tag-info",
            WFAnnounceChipLevel.Warning => "wf-announce-chip-tag-warning",
            WFAnnounceChipLevel.Custom => "wf-announce-chip-tag-notice",
            _ => "wf-announce-chip-tag-advisory",
        };
    }
}
