using System.Linq;
using Content.Shared._WF.Announcements;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Audio;
using Robust.Shared.Audio.Systems;
using Robust.Shared.ContentPack;
using Robust.Shared.Player;
using Robust.Shared.Utility;

namespace Content.Client._WF.Announcements;

/// <summary>
/// The roleplay announcement editor: message, delivery, sound and chip settings on the left, a live preview on the right.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class WFAnnounceWindow : DefaultWindow
{
    [Dependency] private IEntityManager _entities = default!;
    [Dependency] private IResourceManager _resources = default!;

    /// <summary>The sound list stops here; the search narrows it.</summary>
    private const int MaxSoundRows = 300;

    private static readonly ResPath AudioRoot = new("/Audio");
    private static readonly ResPath AnnouncementAudio = new("/Audio/Announcements");

    private static readonly (string Loc, Color Color)[] AccentPresets =
    {
        ("wf-announce-accent-gold", Color.Gold),
        ("wf-announce-accent-command", Color.FromHex("#4a90ff")),
        ("wf-announce-accent-security", Color.FromHex("#ff4040")),
        ("wf-announce-accent-engineering", Color.FromHex("#ffa020")),
        ("wf-announce-accent-medical", Color.FromHex("#5fd7e3")),
        ("wf-announce-accent-corporate", Color.FromHex("#3ec46d")),
        ("wf-announce-accent-syndicate", Color.FromHex("#c0392b")),
        ("wf-announce-accent-grey", Color.FromHex("#b0b0b0")),
    };

    private readonly SharedAudioSystem _audio;
    private readonly StyleBoxFlat _swatch = new();
    private readonly List<string> _sounds = new();

    private Color _accent = Color.Gold;
    private string _soundPath = string.Empty;
    private EntityUid? _previewStream;

    /// <summary>Raised with the filled-in request when Send is pressed.</summary>
    public event Action<WFAnnounceRequest, bool>? OnSend;

    public WFAnnounceWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _audio = _entities.System<SharedAudioSystem>();
        AccentSwatch.PanelOverride = _swatch;

        SenderEdit.IsValid = text => text.Length <= WFAnnounceLimits.MaxSender;
        TitleEdit.IsValid = text => text.Length <= WFAnnounceLimits.MaxTitle;
        ChipTitleEdit.IsValid = text => text.Length <= WFAnnounceLimits.MaxChipTitle;
        ChipTextEdit.IsValid = text => text.Length <= WFAnnounceLimits.MaxChipText;
        BodyEdit.Placeholder = new Rope.Leaf(Loc.GetString("wf-announce-body-placeholder"));

        for (var i = 0; i < AccentPresets.Length; i++)
            AccentSelect.AddItem(Loc.GetString(AccentPresets[i].Loc), i);
        AccentSelect.AddItem(Loc.GetString("wf-announce-accent-custom"), AccentPresets.Length);

        AddOptions(TargetSelect, ("wf-announce-target-everyone", (int) WFAnnounceTarget.Everyone), ("wf-announce-target-map", (int) WFAnnounceTarget.AdminMap));
        AddOptions(SoundModeSelect,
            ("wf-announce-sound-none", (int) WFAnnounceSoundMode.None),
            ("wf-announce-sound-default", (int) WFAnnounceSoundMode.Default),
            ("wf-announce-sound-custom", (int) WFAnnounceSoundMode.Custom));
        AddOptions(ChipLevelSelect,
            ("wf-announce-chip-level-info", (int) WFAnnounceChipLevel.Info),
            ("wf-announce-chip-level-advisory", (int) WFAnnounceChipLevel.Advisory),
            ("wf-announce-chip-level-warning", (int) WFAnnounceChipLevel.Warning),
            ("wf-announce-chip-level-custom", (int) WFAnnounceChipLevel.Custom));
        SoundModeSelect.SelectId(1);
        ChipLevelSelect.SelectId(1);

        VolumeSpin.IsValid = value => value >= WFAnnounceLimits.MinVolume && value <= WFAnnounceLimits.MaxVolume;
        VolumeSpin.InitDefaultButtons();
        VolumeSpin.Value = -2;
        ChipDurationSpin.IsValid = value => value >= 0 && value <= WFAnnounceLimits.MaxChipDuration;
        ChipDurationSpin.InitDefaultButtons();
        ChipDurationSpin.Value = 15;

        SenderEdit.OnTextChanged += _ => Refresh();
        TitleEdit.OnTextChanged += _ => Refresh();
        BodyEdit.OnTextChanged += _ => Refresh();
        MarkupCheck.OnToggled += _ => Refresh();
        AccentSelect.OnItemSelected += OnAccentSelected;
        AccentHex.OnTextChanged += OnAccentHexChanged;
        AccentPickButton.OnToggled += args => AccentPicker.Visible = args.Pressed;
        AccentPicker.SelectorType = ColorSelectorSliders.ColorSelectorType.Hsv;
        AccentPicker.OnColorChanged += color => SetAccent(color, updateHex: true, updatePicker: false);
        TargetSelect.OnItemSelected += args => Select(TargetSelect, args.Id);
        ChatCheck.OnToggled += _ => Refresh();
        SoundModeSelect.OnItemSelected += args => Select(SoundModeSelect, args.Id);
        SoundSearch.OnTextChanged += _ => PopulateSounds();
        SoundList.OnItemSelected += args =>
        {
            _soundPath = (string) SoundList[args.ItemIndex].Metadata!;
            Refresh();
        };
        PreviewSoundButton.OnPressed += _ => PreviewSound();
        StopSoundButton.OnPressed += _ => StopPreview();
        ChipCheck.OnToggled += _ => Refresh();
        ChipLevelSelect.OnItemSelected += args =>
        {
            ChipFlashCheck.Pressed = (WFAnnounceChipLevel) args.Id == WFAnnounceChipLevel.Warning;
            Select(ChipLevelSelect, args.Id);
        };
        ChipFlashCheck.OnToggled += _ => Refresh();
        ChipTitleEdit.OnTextChanged += _ => Refresh();
        ChipTextEdit.OnTextChanged += _ => Refresh();
        ChipDurationSpin.ValueChanged += _ => Refresh();
        SendButton.OnPressed += _ => OnSend?.Invoke(BuildRequest(), !KeepOpenCheck.Pressed);
        OnClose += StopPreview;

        LoadSounds();
        SetAccent(Color.Gold, updateHex: true, updatePicker: true);
    }

    /// <summary>Sound files the picker found under /Audio.</summary>
    public IReadOnlyList<string> Sounds => _sounds;

    /// <summary>Shows the server's answer to the last send.</summary>
    public void SetStatus(string? status, bool error)
    {
        StatusLabel.Text = status ?? string.Empty;
        StatusLabel.FontColorOverride = error ? Color.FromHex("#ff6060") : Color.FromHex("#70d070");
    }

    private static void AddOptions(OptionButton button, params (string Loc, int Id)[] options)
    {
        foreach (var (loc, id) in options)
            button.AddItem(Loc.GetString(loc), id);
    }

    private void Select(OptionButton button, int id)
    {
        button.SelectId(id);
        Refresh();
    }

    private void OnAccentSelected(OptionButton.ItemSelectedEventArgs args)
    {
        AccentSelect.SelectId(args.Id);
        if (args.Id < AccentPresets.Length)
            SetAccent(AccentPresets[args.Id].Color, updateHex: true, updatePicker: true);
    }

    private void OnAccentHexChanged(LineEdit.LineEditEventArgs args)
    {
        if (!Color.TryFromHex(args.Text, out var color))
            return;

        SetAccent(color, updateHex: false, updatePicker: true);
    }

    /// <summary>Sets the colour and syncs the preset list, hex box and sliders that didn't make the change.</summary>
    private void SetAccent(Color color, bool updateHex, bool updatePicker)
    {
        _accent = color.WithAlpha(1f);
        _swatch.BackgroundColor = _accent;

        var hex = _accent.ToHexNoAlpha();
        var preset = Array.FindIndex(AccentPresets, p => p.Color.ToHexNoAlpha() == hex);
        AccentSelect.SelectId(preset >= 0 ? preset : AccentPresets.Length);

        if (updateHex)
            AccentHex.Text = hex;
        if (updatePicker)
            AccentPicker.Color = _accent;
        Refresh();
    }

    /// <summary>Lists every sound file under /Audio, announcement sounds first.</summary>
    private void LoadSounds()
    {
        _sounds.Clear();
        _sounds.AddRange(_resources.ContentFindFiles(AudioRoot)
            .Where(path => path.Extension is "ogg" or "wav")
            .OrderBy(path => path.TryRelativeTo(AnnouncementAudio, out _) ? 0 : 1)
            .ThenBy(path => path.ToString(), StringComparer.OrdinalIgnoreCase)
            .Select(path => path.ToString())
            .Distinct());
        PopulateSounds();
    }

    private void PopulateSounds()
    {
        SoundList.Clear();

        var terms = SoundSearch.Text.Trim().Split(' ', StringSplitOptions.RemoveEmptyEntries);
        var shown = 0;
        foreach (var sound in _sounds)
        {
            if (!terms.All(term => sound.Contains(term, StringComparison.OrdinalIgnoreCase)))
                continue;

            var item = SoundList.AddItem(sound, metadata: sound);
            if (sound == _soundPath)
                item.Selected = true;

            if (++shown >= MaxSoundRows)
                break;
        }
    }

    private string? CurrentSound()
    {
        return (WFAnnounceSoundMode) SoundModeSelect.SelectedId switch
        {
            WFAnnounceSoundMode.Default => WFAnnounceFormat.DefaultSound,
            WFAnnounceSoundMode.Custom when _soundPath.Length > 0 => _soundPath,
            _ => null,
        };
    }

    private void PreviewSound()
    {
        StopPreview();
        if (CurrentSound() is not { } sound)
            return;

        if (!_resources.ContentFileExists(new ResPath(sound)))
        {
            SetStatus(Loc.GetString("wf-announce-error-preview-missing", ("path", sound)), true);
            return;
        }

        _previewStream = _audio.PlayGlobal(new SoundPathSpecifier(sound), Filter.Local(), false, AudioParams.Default.WithVolume(VolumeSpin.Value))?.Entity;
        if (_previewStream == null)
            SetStatus(Loc.GetString("wf-announce-error-preview-failed", ("path", sound)), true);
        else
            SetStatus(null, false);
    }

    private void StopPreview()
    {
        _previewStream = _audio.Stop(_previewStream);
    }

    private WFAnnounceRequest BuildRequest()
    {
        return new WFAnnounceRequest
        {
            Sender = SenderEdit.Text,
            Title = TitleEdit.Text,
            Body = Rope.Collapse(BodyEdit.TextRope),
            AllowMarkup = MarkupCheck.Pressed,
            Accent = _accent,
            Target = (WFAnnounceTarget) TargetSelect.SelectedId,
            PostToChat = ChatCheck.Pressed,
            SoundMode = (WFAnnounceSoundMode) SoundModeSelect.SelectedId,
            SoundPath = _soundPath,
            Volume = VolumeSpin.Value,
            ShowChip = ChipCheck.Pressed,
            ChipLevel = (WFAnnounceChipLevel) ChipLevelSelect.SelectedId,
            ChipTitle = ChipTitleEdit.Text,
            ChipText = ChipTextEdit.Text,
            ChipDuration = ChipDurationSpin.Value,
            ChipFlash = ChipFlashCheck.Pressed,
        };
    }

    /// <summary>Redraws the previews and enables what applies.</summary>
    private void Refresh()
    {
        var request = BuildRequest();

        SoundPicker.Visible = request.SoundMode == WFAnnounceSoundMode.Custom;
        SoundSelectedLabel.Text = _soundPath.Length > 0
            ? Loc.GetString("wf-announce-sound-selected", ("path", _soundPath))
            : Loc.GetString("wf-announce-sound-none-selected");
        PreviewSoundButton.Disabled = CurrentSound() == null;

        ChipOptions.Visible = request.ShowChip;
        ChipPreview.Visible = request.ShowChip;
        ChipPreviewOff.Visible = !request.ShowChip;
        ChipPreview.Set(new WFAnnouncementChipEvent
        {
            Level = request.ChipLevel,
            Accent = request.Accent,
            Title = request.ChipTitle.Trim(),
            Text = request.ChipText.Trim().Length > 0 ? request.ChipText.Trim() : Loc.GetString("wf-announce-chip-text-placeholder"),
            Sender = WFAnnounceFormat.SenderOrDefault(request.Sender),
            Duration = request.ChipDuration,
        });

        var chat = new FormattedMessage();
        if (!request.PostToChat)
            chat.AddMarkupOrThrow(Loc.GetString("wf-announce-preview-chat-off"));
        else if (string.IsNullOrWhiteSpace(request.Body))
            chat.AddMarkupOrThrow(Loc.GetString("wf-announce-preview-chat-empty"));
        else
        {
            chat.PushColor(WFAnnounceFormat.BodyColor(request.Accent));
            if (!chat.TryAddMarkup(WFAnnounceFormat.ChatMarkup(request), out _))
                chat.AddText(WFAnnounceFormat.PlainText(request));
            chat.Pop();
        }
        ChatPreview.SetMessage(chat);

        SendButton.Disabled = !request.PostToChat && !request.ShowChip && request.SoundMode == WFAnnounceSoundMode.None
            || request.PostToChat && string.IsNullOrWhiteSpace(request.Body)
            || request.ShowChip && string.IsNullOrWhiteSpace(request.ChipText)
            || request.SoundMode == WFAnnounceSoundMode.Custom && _soundPath.Length == 0
            || request.Body.Length > WFAnnounceLimits.MaxBody;
    }
}
