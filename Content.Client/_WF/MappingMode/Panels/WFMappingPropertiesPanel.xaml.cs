namespace Content.Client._WF.MappingMode.Panels;

/// <summary>
/// The selected entry with its rotation and placement mode, the build mode and its sub-choice, the z-levels and the
/// session's name, code and limits.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class WFMappingPropertiesPanel : BoxContainer
{
    [Dependency] private IEntityManager _entities = default!;
    [Dependency] private IPlacementManager _placement = default!;
    [Dependency] private IPrototypeManager _prototypes = default!;

    private readonly WFMappingBuildModeSystem _modes = default!;
    private readonly WFMappingLinkSystem _link = default!;
    private readonly MappingZLevelsSystem _zLevels = default!;
    private readonly WFMappingPaletteIcons _icons = new();
    private readonly Dictionary<string, Button> _deviceButtons = new();
    private readonly List<int> _shownDepths = new();
    private int? _shownCurrent;

    /// <summary>Only for the XAML loader; use the constructor that takes what the panel needs.</summary>
    public WFMappingPropertiesPanel()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
    }

    public WFMappingPropertiesPanel(WFMappingBuildModeSystem modes, MappingZLevelsSystem zLevels) : this()
    {
        _modes = modes;
        _zLevels = zLevels;
        _link = _entities.System<WFMappingLinkSystem>();

        var names = _placement.AllModeNames;
        for (var i = 0; i < names.Length; i++)
        {
            PlacementModeMenu.AddItem(names[i], i);
        }

        PlacementModeMenu.OnItemSelected += args =>
        {
            PlacementModeMenu.SelectId(args.Id);
            _modes.SetPlacementMode(args.Id);
        };

        ReplaceButton.Pressed = _placement.Replacement;
        ReplaceButton.OnToggled += args => _placement.Replacement = args.Pressed;

        foreach (var target in Enum.GetValues<WFMappingEraseTarget>())
        {
            EraseTargetMenu.AddItem(Loc.GetString($"wf-mapping-screen-erase-{target.ToString().ToLowerInvariant()}"),
                (int) target);
        }

        EraseTargetMenu.OnItemSelected += args =>
        {
            EraseTargetMenu.SelectId(args.Id);
            _modes.SetEraseTarget((WFMappingEraseTarget) args.Id);
        };

        foreach (var kind in Enum.GetValues<WFMappingShapeKind>())
        {
            ShapeKindMenu.AddItem(Loc.GetString($"wf-mapping-screen-shape-{kind.ToString().ToLowerInvariant()}"),
                (int) kind);
        }

        ShapeKindMenu.OnItemSelected += args =>
        {
            ShapeKindMenu.SelectId(args.Id);
            _modes.SetShapeKind((WFMappingShapeKind) args.Id);
        };

        var fillGroup = new ButtonGroup();
        ShapeFillButton.Group = fillGroup;
        ShapeBorderButton.Group = fillGroup;
        ShapeFillButton.OnPressed += _ => _modes.SetShapeFill(WFMappingShapeFill.Fill);
        ShapeBorderButton.OnPressed += _ => _modes.SetShapeFill(WFMappingShapeFill.Border);

        foreach (var preset in Enum.GetValues<WFMappingPipePreset>())
        {
            PipeColorMenu.AddItem(Loc.GetString($"wf-mapping-screen-pipe-preset-{preset.ToString().ToLowerInvariant()}"),
                (int) preset);
        }

        PipeColorMenu.OnItemSelected += args =>
        {
            PipeColorMenu.SelectId(args.Id);
            _modes.SetPipePreset((WFMappingPipePreset) args.Id);
        };

        PipeCustomEdit.Text = _modes.PipeCustomColor.ToHexNoAlpha();
        PipeCustomEdit.OnTextChanged += args =>
        {
            if (Color.TryFromHex(args.Text.Trim(), out var color))
                _modes.SetPipeCustomColor(color);
        };

        foreach (var layer in Enum.GetValues<AtmosPipeLayer>())
        {
            PipeLayerMenu.AddItem(Loc.GetString($"wf-mapping-screen-pipe-layer-{layer.ToString().ToLowerInvariant()}"),
                (int) layer);
        }

        PipeLayerMenu.OnItemSelected += args =>
        {
            PipeLayerMenu.SelectId(args.Id);
            _modes.SetPipeLayer((AtmosPipeLayer) args.Id);
        };

        PipeJoinButton.OnToggled += args => _modes.SetPipeAutoJoin(args.Pressed);
        PipeReplaceButton.OnToggled += args => _modes.SetPipeReplace(args.Pressed);
        PipePaintButton.OnToggled += args => _modes.SetPipePainting(args.Pressed);
        BuildPipeDevices();

        var linkGroup = new ButtonGroup();
        LinkSignalsButton.Group = linkGroup;
        LinkDevicesButton.Group = linkGroup;
        LinkAccessButton.Group = linkGroup;
        LinkSignalsButton.OnPressed += _ => _link.SetTool(WFMappingLinkTool.Signals);
        LinkDevicesButton.OnPressed += _ => _link.SetTool(WFMappingLinkTool.Devices);
        LinkAccessButton.OnPressed += _ => _link.SetTool(WFMappingLinkTool.Access);
        LinkThresholdsButton.OnPressed += _ => _link.SetTool(WFMappingLinkTool.Thresholds);
        foreach (var (button, tool) in ToolButtons())
        {
            button.OnPressed += _ => _modes.SetTool(tool);
        }
        LinkClearButton.OnPressed += _ => _link.ClearSelection();

        QuickSelectButton.OnPressed += _ =>
        {
            if (_modes.Entry is { } entry)
                _modes.RequestQuickSelect(entry);
        };

        UnsavedLabel.FontColorOverride = Color.FromHex("#e0a030");
        UnsavedButton.OnPressed += _ =>
        {
            if (_modes.Entry is { } entry)
                _modes.UseSpawner(entry);
        };

        LevelUpButton.OnPressed += _ => _zLevels.Move(1);
        LevelDownButton.OnPressed += _ => _zLevels.Move(-1);

        _modes.EntryChanged += OnEntryChanged;
        _modes.ModeChanged += OnModeChanged;
        _modes.SettingsChanged += OnSettingsChanged;
        _modes.SpawnersChanged += UpdateUnsaved;
        _placement.DirectionChanged += OnDirectionChanged;
        _link.Changed += UpdateLink;

        OnEntryChanged(_modes.Entry);
        OnModeChanged(_modes.Mode);
        OnSettingsChanged();
        UpdateLink();
    }

    /// <summary>Drops the subscriptions, before the panel is thrown away.</summary>
    public void Unbind()
    {
        _modes.EntryChanged -= OnEntryChanged;
        _modes.ModeChanged -= OnModeChanged;
        _modes.SettingsChanged -= OnSettingsChanged;
        _modes.SpawnersChanged -= UpdateUnsaved;
        _placement.DirectionChanged -= OnDirectionChanged;
        _link.Changed -= UpdateLink;
    }

    /// <summary>Reads the z-stack and the session again; the screen controller calls it while the panel shows.</summary>
    public void Refresh(WFMappingSessionInfo? session, List<int> depths, int current)
    {
        UpdateLevels(depths, current);
        ReplaceButton.Pressed = _placement.Replacement;

        if (session == null)
        {
            SessionLabel.Text = string.Empty;
            LimitsLabel.Text = string.Empty;
            return;
        }

        SessionLabel.Text = Loc.GetString("wf-mapping-screen-session",
            ("name", session.Name),
            ("code", session.Code));
        LimitsLabel.Text = Status(session.Limits);
    }

    /// <summary>The limits line: grids, entities and the map area.</summary>
    public static string Status(WFMappingLimitsState limits)
    {
        return Loc.GetString("wf-mapping-mode-menu-status",
            ("grids", limits.Grids),
            ("maxGrids", limits.MaxGrids),
            ("entities", limits.Entities.ToString("N0", CultureInfo.InvariantCulture)),
            ("maxEntities", limits.MaxEntities.ToString("N0", CultureInfo.InvariantCulture)),
            ("size", limits.MapSize));
    }

    private void UpdateLevels(List<int> depths, int current)
    {
        if (_shownCurrent == current && _shownDepths.Count == depths.Count && _shownDepths.TrueForAll(depths.Contains))
            return;

        _shownDepths.Clear();
        _shownDepths.AddRange(depths);
        _shownCurrent = current;

        LevelList.RemoveAllChildren();
        for (var i = depths.Count - 1; i >= 0; i--)
        {
            var depth = depths[i];
            var button = new Button
            {
                Text = Loc.GetString(depth == 0 ? "wf-mapping-tools-level-ground" : "wf-mapping-tools-level",
                    ("depth", depth)),
                ToggleMode = true,
                Pressed = depth == current,
                HorizontalExpand = true,
            };
            button.OnPressed += _ =>
            {
                button.Pressed = depth == current;
                _zLevels.Move(depth - current);
            };
            LevelList.AddChild(button);
        }

        LevelUpButton.Disabled = depths.Count == 0 || current >= depths[^1];
        LevelDownButton.Disabled = depths.Count == 0 || current <= depths[0];
    }

    private void OnEntryChanged(WFMappingPaletteEntry? entry)
    {
        QuickSelectButton.Disabled = entry == null;
        if (entry is not { } chosen)
        {
            EntryIcon.Texture = null;
            EntryName.Text = Loc.GetString("wf-mapping-screen-nothing-selected");
            EntryId.Text = string.Empty;
        }
        else
        {
            EntryIcon.Texture = _icons.Get(chosen);
            EntryIcon.Modulate = chosen.Color ?? Color.White;
            EntryName.Text = _icons.Name(chosen);
            EntryId.Text = Loc.GetString($"wf-mapping-screen-kind-{chosen.Kind.ToString().ToLowerInvariant()}",
                ("id", chosen.Id));
        }

        UpdateUnsaved();
        UpdateRotation();
    }

    /// <summary>Shows the spawner hint under an entry that won't be saved, when a spawner would stand in for it.</summary>
    private void UpdateUnsaved()
    {
        var hint = _modes.Entry is { } entry ? _modes.SpawnerHint(entry) : null;
        UnsavedRow.Visible = hint != null;
        UnsavedLabel.Text = hint ?? string.Empty;
        UnsavedLabel.ToolTip = hint;
    }

    private void OnModeChanged(WFMappingBuildMode mode)
    {
        ModeLabel.Text = Loc.GetString("wf-mapping-screen-mode-current",
            ("mode", Loc.GetString($"wf-mapping-screen-mode-{mode.ToString().ToLowerInvariant()}")));
        EraseRow.Visible = mode == WFMappingBuildMode.Erase;
        ShapeRow.Visible = mode == WFMappingBuildMode.Shape;
        PipeBox.Visible = mode == WFMappingBuildMode.Pipe;
        LinkBox.Visible = mode == WFMappingBuildMode.Link;
        ToolBox.Visible = mode == WFMappingBuildMode.Wrench;
        UpdateShapeFill();
    }

    private void UpdateShapeFill()
    {
        ShapeFillRow.Visible = _modes.Mode == WFMappingBuildMode.Shape && _modes.ShapeKind != WFMappingShapeKind.Line;
        ShapeFillButton.Pressed = _modes.ShapeFill == WFMappingShapeFill.Fill;
        ShapeBorderButton.Pressed = _modes.ShapeFill == WFMappingShapeFill.Border;
    }

    private void OnSettingsChanged()
    {
        EraseTargetMenu.TrySelectId((int) _modes.EraseTarget);
        ShapeKindMenu.TrySelectId((int) _modes.ShapeKind);
        UpdateShapeFill();
        UpdatePipe();
        UpdateTools();
        PlacementModeMenu.TrySelectId(_modes.PlacementModeIndex);
        UpdateRotation();
    }

    private void UpdatePipe()
    {
        PipeColorMenu.TrySelectId((int) _modes.PipePreset);
        PipeLayerMenu.TrySelectId((int) _modes.PipeLayer);
        PipeCustomRow.Visible = _modes.PipePreset == WFMappingPipePreset.Custom;
        PipeSwatch.Visible = _modes.PipeColor != null;
        PipeSwatch.PanelOverride = new StyleBoxFlat { BackgroundColor = _modes.PipeColor ?? Color.Transparent };
        PipeJoinButton.Pressed = _modes.PipeAutoJoin;
        PipeReplaceButton.Pressed = _modes.PipeReplace;
        PipePaintButton.Pressed = _modes.PipePainting;
        PipeFacingLabel.Text = Loc.GetString("wf-mapping-screen-pipe-facing", ("facing", _modes.PipeFacingName()));

        foreach (var (id, button) in _deviceButtons)
        {
            button.Pressed = _modes.PipeDevice == id;
        }

        PipeDeviceLabel.Text = _modes.PipeDevice is { } device
            ? DeviceName(device)
            : Loc.GetString("wf-mapping-screen-pipe-devices-hint");
    }

    /// <summary>One icon button per atmos device that exists and shows in the spawn menu.</summary>
    private void BuildPipeDevices()
    {
        foreach (var id in MappingToolsPipeDevices.Ids)
        {
            if (!_prototypes.TryIndex<EntityPrototype>(id, out var prototype) || prototype.HideSpawnMenu)
                continue;

            var button = new Button
            {
                ToggleMode = true,
                SetSize = new Vector2(36, 36),
                ToolTip = DeviceName(id),
                TooltipDelay = 0f,
            };
            button.AddChild(new TextureRect
            {
                Texture = _icons.Entity(id),
                Stretch = TextureRect.StretchMode.KeepAspectCentered,
                SetSize = new Vector2(32, 32),
                HorizontalAlignment = HAlignment.Center,
                VerticalAlignment = VAlignment.Center,
                MouseFilter = MouseFilterMode.Ignore,
            });
            button.OnToggled += args => _modes.SetPipeDevice(args.Pressed ? id : null);
            PipeDeviceGrid.AddChild(button);
            _deviceButtons[id] = button;
        }
    }

    /// <summary>A device's name, with its suffix when it has one.</summary>
    private string DeviceName(string id)
    {
        if (!_prototypes.TryIndex<EntityPrototype>(id, out var prototype))
            return id;

        return prototype.EditorSuffix is { } suffix
            ? Loc.GetString("wf-mapping-screen-pipe-device-tooltip-suffix", ("name", prototype.Name), ("suffix", suffix))
            : prototype.Name;
    }

    private (Button Button, WFMappingTool Tool)[] ToolButtons()
    {
        return
        [
            (ToolWrenchButton, WFMappingTool.Wrench),
            (ToolBoltsButton, WFMappingTool.Bolts),
            (ToolWeldButton, WFMappingTool.Weld),
            (ToolLockButton, WFMappingTool.Lock),
            (ToolPanelButton, WFMappingTool.Panel),
            (ToolDoorButton, WFMappingTool.Door),
        ];
    }

    private void UpdateTools()
    {
        foreach (var (button, tool) in ToolButtons())
        {
            button.Pressed = _modes.Tool == tool;
        }
    }

    private void UpdateLink()
    {
        LinkSignalsButton.Pressed = _link.Tool == WFMappingLinkTool.Signals;
        LinkDevicesButton.Pressed = _link.Tool == WFMappingLinkTool.Devices;
        LinkAccessButton.Pressed = _link.Tool == WFMappingLinkTool.Access;
        LinkThresholdsButton.Pressed = _link.Tool == WFMappingLinkTool.Thresholds;

        var selected = _link.Source ?? _link.Holder;
        LinkClearButton.Disabled = selected == null;
        LinkSelectedLabel.Text = selected is { } uid && _entities.TryGetComponent(uid, out MetaDataComponent? meta)
            ? Loc.GetString("wf-mapping-link-selected", ("name", meta.EntityName))
            : Loc.GetString($"wf-mapping-link-hint-{_link.Tool.ToString().ToLowerInvariant()}");
    }

    private void OnDirectionChanged(object? sender, EventArgs e)
    {
        UpdateRotation();
    }

    private void UpdateRotation()
    {
        RotationLabel.Text = _modes.Entry is { Kind: WFMappingPaletteKind.Decal }
            ? Loc.GetString("wf-mapping-screen-rotation-degrees", ("degrees", (int) _modes.DecalSettings.Rotation))
            : Loc.GetString("wf-mapping-screen-rotation", ("direction", _placement.Direction.ToString()));
    }
}
