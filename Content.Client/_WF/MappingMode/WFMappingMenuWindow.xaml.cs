namespace Content.Client._WF.MappingMode;

/// <summary>
/// The in-game Mapping window: Session, Save and Library tabs. <see cref="WFMappingMenuUIController"/> wires it up.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class WFMappingMenuWindow : FancyWindow
{
    [Dependency] private IGameTiming _timing = default!;

    private static readonly Color SuccessColor = Color.FromHex("#7fd17f");
    private static readonly Color FailureColor = Color.FromHex("#ff7a7a");

    private const int GridsTab = 1;
    private const int ReferenceTab = 2;

    private WFMappingSessionInfo? _session;
    private int? _namedSession;
    private List<MappingMapFile> _referenceFiles = new();
    private string? _selectedReference;

    public event Action<NetUserId>? KickRequested;
    public event Action<int>? AutosaveRequested;
    public event Action<string>? ReferencePicked;

    /// <summary>Raised when the Reference tab opens, to fill its list.</summary>
    public event Action? ReferencesWanted;

    /// <summary>Raised a moment after a file is picked, so running down the list doesn't ask for each one.</summary>
    public event Action<string>? PreviewWanted;
    public event Action<NetEntity>? GoToGridRequested;
    public event Action<NetEntity>? DeleteGridRequested;

    /// <summary>Raised every few seconds while the Grids tab shows, so the grid list follows edits.</summary>
    public event Action? GridsWanted;

    private static readonly TimeSpan GridsInterval = TimeSpan.FromSeconds(3);
    private TimeSpan _nextGrids;

    private static readonly TimeSpan PreviewDelay = TimeSpan.FromSeconds(0.2);
    private TimeSpan? _previewAt;

    public WFMappingMenuWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        HelpGuidebookIds = new List<ProtoId<GuideEntryPrototype>> { WFMappingGuide.Root };

        Tabs.SetTabTitle(0, Loc.GetString("wf-mapping-mode-menu-tab-session"));
        Tabs.SetTabTitle(GridsTab, Loc.GetString("wf-mapping-mode-menu-tab-grids"));
        Tabs.SetTabTitle(ReferenceTab, Loc.GetString("wf-mapping-mode-menu-tab-reference"));
        Tabs.SetTabTitle(3, Loc.GetString("wf-mapping-mode-menu-tab-save"));
        Tabs.SetTabTitle(4, Loc.GetString("wf-mapping-mode-menu-tab-library"));
        Tabs.OnTabChanged += tab =>
        {
            if (tab == ReferenceTab)
                ReferencesWanted?.Invoke();
        };

        foreach (var minutes in WFMappingAutosaveSteps.Minutes)
        {
            AutosaveOption.AddItem(minutes == 0
                ? Loc.GetString("wf-mapping-mode-menu-autosave-off")
                : Loc.GetString("wf-mapping-mode-menu-autosave-step", ("minutes", minutes)), minutes);
        }

        AutosaveOption.OnItemSelected += args =>
        {
            if (_session == null || args.Id == _session.AutosaveMinutes)
                return;

            AutosaveOption.SelectId(args.Id);
            AutosaveRequested?.Invoke(args.Id);
        };

        LibraryList.ShowOpen = false;
        UploadRow.ShowOpen = false;
        ReferenceInfo.Text = Loc.GetString("wf-mapping-mode-menu-reference-pick");
        ReferenceSearch.OnTextChanged += _ => PopulateReferences();
        ReferenceList.OnItemSelected += args => SelectReference(ReferenceList[args.ItemIndex].Metadata as string);
        ReferenceList.OnItemDeselected += _ => SelectReference(null);
        ReferencePlaceButton.OnPressed += _ =>
        {
            if (_selectedReference != null)
                ReferencePicked?.Invoke(_selectedReference);
        };
    }

    /// <summary>Shows the session, or Return to lobby for an admin observer when there is none.</summary>
    public void SetSession(WFMappingSessionInfo? session, NetUserId? self, bool adminObserver)
    {
        _session = session;
        NoSessionBox.Visible = session == null;
        ReturnButton.Visible = session == null && adminObserver;
        SessionBox.Visible = session != null;
        if (session == null && Tabs.CurrentTab is GridsTab or ReferenceTab)
            Tabs.CurrentTab = 0;

        Tabs.SetTabVisible(GridsTab, session != null);
        Tabs.SetTabVisible(ReferenceTab, session != null);

        if (session == null)
        {
            UpdateSaveTimes();
            return;
        }

        var owner = self == session.Owner;
        SessionNameLabel.Text = session.Name;
        CodeLabel.Text = Loc.GetString("wf-mapping-mode-menu-code", ("code", session.Code));
        NewCodeButton.Visible = owner;

        var limits = session.Limits;
        StatusLabel.Text = Loc.GetString("wf-mapping-mode-menu-status",
            ("grids", limits.Grids),
            ("maxGrids", limits.MaxGrids),
            ("entities", limits.Entities.ToString("N0", CultureInfo.InvariantCulture)),
            ("maxEntities", limits.MaxEntities.ToString("N0", CultureInfo.InvariantCulture)),
            ("size", limits.MapSize));

        TestLabel.Visible = session.Test != null;
        if (session.Test is { } test)
        {
            TestLabel.Text = Loc.GetString("wf-mapping-mode-menu-testing",
                ("testers", string.Join(", ", test.Testers)),
                ("minutes", Math.Max(0, (int) Math.Ceiling((test.Ends - _timing.CurTime).TotalMinutes))));
        }

        MemberList.RemoveAllChildren();
        foreach (var member in session.Members)
        {
            var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 4 };
            row.AddChild(new Label
            {
                Text = Loc.GetString("wf-mapping-mode-menu-member", ("name", member.Name),
                    ("owner", member.User == session.Owner ? "yes" : "no"),
                    ("away", member.Present ? "no" : "yes")),
                HorizontalExpand = true,
                ClipText = true,
            });

            if (owner && member.User != session.Owner)
            {
                var user = member.User;
                var kick = new ConfirmButton { Text = Loc.GetString("wf-mapping-mode-menu-kick") };
                kick.OnPressed += _ => KickRequested?.Invoke(user);
                row.AddChild(kick);
            }

            MemberList.AddChild(row);
        }

        AutosaveOption.SelectId(session.AutosaveMinutes);
        AutosaveOption.Disabled = !owner;
        AutosaveHint.Text = owner ? string.Empty : Loc.GetString("wf-mapping-mode-menu-autosave-owner-only");

        if (_namedSession != session.Id)
        {
            _namedSession = session.Id;
            SaveNameEdit.Text = session.Name;
        }

        SaveNameEdit.PlaceHolder = session.Name;
        DirtyLabel.Text = Loc.GetString(session.Dirty ? "wf-mapping-mode-menu-dirty" : "wf-mapping-mode-menu-clean");
        UpdateSaveTimes();
    }

    public void SetLibrary(WFMappingLibraryEvent? library)
    {
        LibraryList.SetLibrary(library);
        LibraryUsage.Text = library == null
            ? string.Empty
            : Loc.GetString("wf-mapping-mode-library-usage",
                ("maps", library.Maps.Count),
                ("maxMaps", library.MaxMaps),
                ("used", WFMappingLibraryList.FormatMiB(library.Bytes)),
                ("max", WFMappingLibraryList.FormatMiB(library.MaxBytes)));
    }

    /// <summary>One row per grid on every level: level, tiles, entities, Go to and Delete.</summary>
    public void SetGrids(List<WFMappingGridInfo> grids)
    {
        GridList.RemoveAllChildren();
        NextGridButton.Disabled = grids.Count == 0;
        GridsHint.Text = grids.Count == 0
            ? Loc.GetString("wf-mapping-ship-menu-grids-none")
            : Loc.GetString("wf-mapping-ship-menu-grids-count", ("count", grids.Count));

        foreach (var grid in grids)
        {
            var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 4 };
            row.AddChild(new Label
            {
                Text = Loc.GetString("wf-mapping-ship-menu-grid-row", ("depth", grid.Depth), ("name", grid.Name),
                    ("tiles", grid.Tiles), ("entities", grid.Entities)),
                HorizontalExpand = true,
                ClipText = true,
            });

            var target = grid.Grid;
            var goTo = new Button { Text = Loc.GetString("wf-mapping-ship-menu-goto") };
            goTo.OnPressed += _ => GoToGridRequested?.Invoke(target);
            row.AddChild(goTo);

            var delete = new Button
            {
                Text = Loc.GetString("wf-mapping-mode-menu-delete-grid-row"),
                ToolTip = Loc.GetString("wf-mapping-mode-menu-delete-grid-row-tooltip"),
                TooltipDelay = 0,
                StyleClasses = { "Caution" },
            };
            delete.OnPressed += _ => DeleteGridRequested?.Invoke(target);
            row.AddChild(delete);
            GridList.AddChild(row);
        }
    }

    /// <summary>Shows the confirm strip for the grid waiting on deletion, or hides it.</summary>
    public void SetPendingDelete(WFMappingGridInfo? grid)
    {
        DeleteConfirmBox.Visible = grid != null;
        if (grid is not { } pending)
            return;

        DeleteConfirmLabel.Text = string.IsNullOrEmpty(pending.Name)
            ? Loc.GetString("wf-mapping-mode-menu-delete-grid-preview-unknown")
            : Loc.GetString("wf-mapping-mode-menu-delete-grid-preview", ("name", pending.Name),
                ("tiles", pending.Tiles), ("entities", pending.Entities));
    }

    public void SetReferenceFiles(List<MappingMapFile> files)
    {
        _referenceFiles = files;
        PopulateReferences();
    }

    /// <summary>Shows a file's floor plan and size, if it is the file still picked.</summary>
    public void SetPreview(WFMappingReferencePreviewEvent ev)
    {
        if (ev.Path != _selectedReference)
            return;

        ReferencePreview.SetPreview(ev.Preview);
        ReferenceInfo.Text = ev.Preview is { } preview ? PreviewInfo(preview) : ev.Error ?? string.Empty;
    }

    private static string PreviewInfo(WFMappingReferencePreview preview)
    {
        Box2? bounds = null;
        foreach (var grid in preview.Grids)
        {
            var matrix = Matrix3Helpers.CreateTransform(grid.Offset, grid.Rotation);
            foreach (var rect in grid.Floor)
            {
                var box = matrix.TransformBox(new Box2(rect.Left, rect.Bottom, rect.Right, rect.Top));
                bounds = bounds is { } union ? union.Union(box) : box;
            }
        }

        return Loc.GetString("wf-mapping-mode-menu-reference-stats",
            ("grids", preview.Grids.Count),
            ("width", (int) MathF.Round(bounds?.Width ?? 0)),
            ("height", (int) MathF.Round(bounds?.Height ?? 0)),
            ("tiles", preview.Tiles.ToString("N0", CultureInfo.InvariantCulture)),
            ("entities", preview.Entities.ToString("N0", CultureInfo.InvariantCulture)),
            ("size", WFMappingLibraryList.FormatMiB(preview.Bytes)));
    }

    public void SetResult(WFMappingResult? result)
    {
        ShowResult(ResultLabel, result);
    }

    /// <summary>Shows an outcome on a label, green or red.</summary>
    public static void ShowResult(Label label, WFMappingResult? result)
    {
        label.Text = result?.Text ?? string.Empty;
        label.FontColorOverride = result is { Success: false } ? FailureColor : SuccessColor;
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        UpdateSaveTimes();

        var now = _timing.RealTime;
        if (_previewAt is { } previewAt && now >= previewAt)
        {
            _previewAt = null;
            if (_selectedReference != null)
                PreviewWanted?.Invoke(_selectedReference);
        }

        if (now < _nextGrids || !GridsBox.VisibleInTree)
            return;

        _nextGrids = now + GridsInterval;
        GridsWanted?.Invoke();
    }

    private void UpdateSaveTimes()
    {
        if (_session == null)
        {
            LastSavedLabel.Text = string.Empty;
            NextAutosaveLabel.Text = string.Empty;
            DirtyLabel.Text = string.Empty;
            return;
        }

        LastSavedLabel.Text = _session.LastSaved is { } saved
            ? Loc.GetString("wf-mapping-mode-menu-last-saved", ("time", WFMappingLibraryList.FormatStamp(saved)))
            : Loc.GetString("wf-mapping-mode-menu-never-saved");

        if (_session.NextAutosave is not { } next)
        {
            NextAutosaveLabel.Text = Loc.GetString("wf-mapping-mode-menu-autosave-disabled");
            return;
        }

        var left = next - _timing.CurTime;
        if (left < TimeSpan.Zero)
            left = TimeSpan.Zero;

        NextAutosaveLabel.Text = Loc.GetString("wf-mapping-mode-menu-next-autosave",
            ("time", left.ToString(@"m\:ss", CultureInfo.InvariantCulture)));
    }

    private void PopulateReferences()
    {
        ReferenceList.Clear();
        var filter = ReferenceSearch.Text.Trim();

        foreach (var source in Enum.GetValues<MappingMapSource>())
        {
            var header = false;
            foreach (var file in _referenceFiles)
            {
                var shown = ShortPath(file);
                if (file.Source != source ||
                    filter.Length > 0 && !shown.Contains(filter, StringComparison.OrdinalIgnoreCase))
                {
                    continue;
                }

                if (!header)
                {
                    ReferenceList.AddItem(Loc.GetString(
                            $"wf-mapping-mode-menu-reference-source-{source.ToString().ToLowerInvariant()}"),
                        selectable: false).Disabled = true;
                    header = true;
                }

                var item = ReferenceList.AddItem("  " + shown, metadata: file.Path);
                item.TooltipText = shown;
                item.Selected = file.Path == _selectedReference;
            }
        }

        ReferencePlaceButton.Disabled = _selectedReference == null;
    }

    /// <summary>Library files drop the <c>/Mapping/Library/&lt;user&gt;/</c> prefix.</summary>
    private static string ShortPath(MappingMapFile file)
    {
        var path = file.Path;
        if (file.Source != MappingMapSource.Saved)
            return path;

        var root = WFMappingLibraryNames.Root.ToString() + "/";
        if (!path.StartsWith(root, StringComparison.Ordinal))
            return path;

        var user = path.IndexOf('/', root.Length);
        return user < 0 ? path : path[(user + 1)..];
    }

    private void SelectReference(string? path)
    {
        if (_selectedReference == path)
            return;

        _selectedReference = path;
        ReferencePlaceButton.Disabled = path == null;
        ReferencePreview.SetPreview(null);
        ReferenceInfo.Text = Loc.GetString(path == null
            ? "wf-mapping-mode-menu-reference-pick"
            : "wf-mapping-mode-menu-reference-loading");
        _previewAt = path == null ? null : _timing.RealTime + PreviewDelay;
    }
}
