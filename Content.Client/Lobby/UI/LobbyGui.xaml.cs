using Content.Client.Message;
using Content.Client.GameTicking.Managers; // WOLFGATE(RoundSetup)
using Content.Client._WF.RoundSetup; // WOLFGATE(RoundSetup)
using Content.Client._WF.Feedback; // WOLFGATE(Feedback)
using Content.Client._WF.LoreBook; // WOLFGATE(LoreBook)
using Content.Client.UserInterface.Systems.EscapeMenu;
using Robust.Client.AutoGenerated;
using Robust.Client.Console;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.Lobby.UI
{
    [GenerateTypedNameReferences]
    public sealed partial class LobbyGui : UIScreen
    {
        [Dependency] private IClientConsoleHost _consoleHost = default!;

        public LobbyGui()
        {
            RobustXamlLoader.Load(this);
            IoCManager.InjectDependencies(this);
            SetAnchorPreset(MainContainer, LayoutPreset.Wide);
            SetAnchorPreset(Background, LayoutPreset.Wide);
            SetAnchorPreset(AnimatedBackground, LayoutPreset.Wide); // WOLFGATE(Symphony): the GIF background covers the screen as the still one does
            SetAnchorPreset(SkinScanlines, LayoutPreset.Wide); // WOLFGATE(Stylesheets): skin scanlines cover the whole screen
            SetAnchorPreset(ShenaniganLayer, LayoutPreset.Wide); // WOLFGATE(LobbyShenanigans): the lobby fun plays over the whole screen
            InitializeRoundSetupHome(); // WOLFGATE(RoundSetup): unify character and crew preparation controls

            LobbySong.SetMarkup(Loc.GetString("lobby-state-song-no-song-text"));

            // WOLFGATE(RoundSetup): expose group setup before the round starts
            RoundSetupButton.OnPressed += _ => UserInterfaceManager.GetUIController<WFRoundSetupUIController>().OpenCrews();

            // WOLFGATE(Feedback): bug report and suggestion entry in the lobby
            FeedbackButton.OnPressed += _ => UserInterfaceManager.GetUIController<FeedbackUIController>().ToggleWindow();

            LeaveButton.OnPressed += _ => _consoleHost.ExecuteCommand("disconnect");
            OptionsButton.OnPressed += _ => UserInterfaceManager.GetUIController<OptionsUIController>().ToggleWindow();
            LoreBookButton.OnPressed += _ => UserInterfaceManager.GetUIController<WFLoreBookUIController>().Toggle(); // WOLFGATE(LoreBook)

            // WOLFGATE(Stylesheets) START: menu entry for character setup; un-readies first like LobbyState.OnSetupPressed
            CustomizeButton.OnPressed += _ =>
            {
                ClearRoundSetupReadiness(); // WOLFGATE(RoundSetup): character editing clears crew readiness too
            // WOLFGATE END
                // WOLFGATE(RoundSetup) START: Join no longer toggles, but character edits still clear pregame readiness
                // if (ReadyButton.ToggleMode)
                if (!IoCManager.Resolve<IEntityManager>().System<ClientGameTicker>().IsGameStarted)
                // WOLFGATE END
                // WOLFGATE(Stylesheets) START: open the existing character setup screen after clearing readiness
                    _consoleHost.ExecuteCommand("toggleready False");
                SwitchState(LobbyGuiState.CharacterSetup);
            };
            // WOLFGATE END
        }

        public void SwitchState(LobbyGuiState state)
        {
            DefaultState.Visible = false;
            CharacterSetupState.Visible = false;

            switch (state)
            {
                case LobbyGuiState.Default:
                    DefaultState.Visible = true;
                    RightSide.Visible = true;
                    break;
                case LobbyGuiState.CharacterSetup:
                    CharacterSetupState.Visible = true;

                    // WOLFGATE(Stylesheets) START: the creator takes the whole screen, so the chat dock always hides
                    // var actualWidth = (float) UserInterfaceManager.RootControl.PixelWidth;
                    // var setupWidth = (float) LeftSide.PixelWidth;
                    //
                    // if (1 - (setupWidth / actualWidth) > 0.30)
                    // {
                    //     RightSide.Visible = false;
                    // }
                    RightSide.Visible = false;
                    // WOLFGATE END

                    UserInterfaceManager.GetUIController<LobbyUIController>().ReloadCharacterSetup();

                    break;
            }
        }

        public enum LobbyGuiState : byte
        {
            /// <summary>
            ///  The default state, i.e., what's seen on launch.
            /// </summary>
            Default,
            /// <summary>
            ///  The character setup state.
            /// </summary>
            CharacterSetup
        }
    }
}
