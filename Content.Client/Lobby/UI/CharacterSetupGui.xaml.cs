namespace Content.Client.Lobby.UI
{
    /// <summary>
    /// Holds the entire character setup GUI, from character picks to individual character editing.
    /// </summary>
    [GenerateTypedNameReferences]
    public sealed partial class CharacterSetupGui : Control
    {
        [Dependency] private IClientPreferencesManager _preferencesManager = default!;
        [Dependency] private IEntityManager _entManager = default!;
        [Dependency] private IPrototypeManager _protomanager = default!;
        [Dependency] private IResourceCache _resourceCache = default!;
        [Dependency] private IConfigurationManager _cfg = default!;
        [Dependency] private ILogManager _logManager = default!; // WOLFGATE: logs characters that can't be previewed

        private readonly Button _createNewCharacterButton;

        public event Action<int>? SelectCharacter;
        // WOLFGATE(Humanoid) START: new-character request, so unsaved edits can be confirmed first
        /// <summary>Raised instead of creating a character directly.</summary>
        public event Action? NewCharacter;
        // WOLFGATE END
        public event Action<int>? DeleteCharacter;

        public CharacterSetupGui(HumanoidProfileEditor profileEditor)
        {
            RobustXamlLoader.Load(this);
            IoCManager.InjectDependencies(this);

            // WOLFGATE(Stylesheets) START: skinned backdrop for the creator shell
            // upstream original, kept for merges:
            // var panelTex = _resourceCache.GetTexture("/Textures/Interface/Nano/button.svg.96dpi.png");
            // var back = new StyleBoxTexture
            // {
            //     Texture = panelTex,
            //     Modulate = new Color(37, 37, 42)
            // };
            // back.SetPatchMargin(StyleBox.Margin.All, 10);
            //
            // BackgroundPanel.PanelOverride = back;
            BackgroundPanel.StyleClasses.Add(StyleWolfgate.StyleClassCreatorBackdrop);
            // WOLFGATE END

            _createNewCharacterButton = new Button
            {
                Text = Loc.GetString("character-setup-gui-create-new-character-button"),
            };

            _createNewCharacterButton.OnPressed += args =>
            {
                NewCharacter?.Invoke(); // WOLFGATE(Humanoid): was CreateCharacter + ReloadCharacterPickers here
                args.Event.Handle();
            };

            CharEditor.AddChild(profileEditor);
            RulesButton.OnPressed += _ => new RulesAndInfoWindow().Open();

            StatsButton.OnPressed += _ => new PlaytimeStatsWindow().OpenCentered();

            _cfg.OnValueChanged(CCVars.SeeOwnNotes, p => AdminRemarksButton.Visible = p, true);
        }

        // WOLFGATE(InRoundCreator) START: the slot shown can differ from the selected one in a round
        /// <summary>The slot to highlight in the list; null means the selected character.</summary>
        public int? EditedSlot;

        private bool _inRound;

        /// <summary>
        /// Keeps the selected character, the one being played, from being deleted. The window has its own close.
        /// </summary>
        public void SetInRound()
        {
            _inRound = true;
            CloseButton.Visible = false;
        }
        // WOLFGATE END

        /// <summary>
        /// Disposes and reloads all character picker buttons from the preferences data.
        /// </summary>
        public void ReloadCharacterPickers()
        {
            _createNewCharacterButton.Orphan();
            Characters.DisposeAllChildren();

            var numberOfFullSlots = 0;
            var characterButtonsGroup = new ButtonGroup();

            if (!_preferencesManager.ServerDataLoaded)
            {
                return;
            }

            _createNewCharacterButton.ToolTip =
                Loc.GetString("character-setup-gui-create-new-character-button-tooltip",
                    ("maxCharacters", _preferencesManager.Settings!.MaxCharacterSlots));

            var selectedSlot = _preferencesManager.Preferences?.SelectedCharacterIndex;

            foreach (var (slot, character) in _preferencesManager.Preferences!.Characters)
            {
                numberOfFullSlots++;
                // WOLFGATE START: a character this build cannot preview is skipped instead of aborting the loop
                // Aborting left the player without the rest of their characters and without the create-character
                // button.
                CharacterPickerButton characterPickerButton;
                try
                {
                    characterPickerButton = new CharacterPickerButton(_entManager,
                        _protomanager,
                        characterButtonsGroup,
                        character,
                        slot == (EditedSlot ?? selectedSlot)); // WOLFGATE(InRoundCreator): was slot == selectedSlot
                }
                catch (Exception e)
                {
                    _logManager.GetSawmill("lobby").Error($"Could not show character in slot {slot}: {e}");
                    continue;
                }
                // WOLFGATE END

                // WOLFGATE(InRoundCreator): the character being played cannot be deleted, the server refuses it
                if (_inRound && slot == selectedSlot)
                    characterPickerButton.HideDelete();

                Characters.AddChild(characterPickerButton);

                characterPickerButton.OnPressed += args =>
                {
                    SelectCharacter?.Invoke(slot);
                };

                characterPickerButton.OnDeletePressed += () =>
                {
                    DeleteCharacter?.Invoke(slot);
                };
            }

            _createNewCharacterButton.Disabled = numberOfFullSlots >= _preferencesManager.Settings.MaxCharacterSlots;
            Characters.AddChild(_createNewCharacterButton);
        }
    }
}
