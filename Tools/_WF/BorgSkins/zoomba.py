#!/usr/bin/env python3
"""Converts Meridian Rift's Zoomba borg skins into borg subtype RSIs.

    python Tools/_WF/BorgSkins/zoomba.py <dir with the .dmi files> <Meridian Rift commit sha>

The folder holds modular_nova/modules/borgs/icons/robots*.dmi. Writes Resources/Textures/_WF/BorgSkins/Small and the
zoomba_subtypes.yml, zoomba_chassis.yml and zoomba_chassis.ftl files; run recolor.py afterwards for the faction
variants. A Zoomba has no eyes, so its status lights (the sheet's lamp overlay) show while it has a mind.
"""
import json
import shutil
import sys
from pathlib import Path

from convert import DEPTS, LOCALE, PROTOTYPES, ROOT, TEXTURES, TYPES, Dmi, write_state

FOLDER = 'modular_nova/modules/borgs/icons'
SOURCE = 'https://github.com/Aphelion-Moon/Meridian-Rift/blob/{sha}/{folder}/{file}'
PARENTS = {'generic': 'BorgChassisGeneric', 'engineering': 'BorgChassisEngineer', 'mining': 'BorgChassisMining',
           'janitor': 'BorgChassisJanitor', 'medical': 'BorgChassisMedical', 'service': 'BorgChassisService'}

# (sheet, icon state, folder and ID part, borg type, chassis name).
SKINS = [('robots.dmi', 'zoomba_standard', 'Standard', 'generic', 'Zoomba cyborg')]
for _dept, _sheet, _icon in (('eng', 'eng', 'engi'), ('jani', 'jani', 'jani'), ('med', 'med', 'med'),
                             ('mine', 'mine', 'miner'), ('serv', 'serv', 'green'), ('cargo', 'cargo', 'cargo'),
                             ('sec', 'sec', 'sec'), ('pk', 'pk', 'peace')):
    _folder, _type, _word = DEPTS[_dept]
    SKINS.append((f'robots_{_sheet}.dmi', f'zoomba_{_icon}', _folder, _type, f'Zoomba {_word} cyborg'))


def main():
    source, sha = Path(sys.argv[1]), sys.argv[2]
    shutil.rmtree(TEXTURES / 'Small', ignore_errors=True)

    subtypes, chassis, names = [], [], []
    for sheet, icon, folder, borg_type, name in SKINS:
        dmi = Dmi(source / sheet, FOLDER)
        body = TYPES[borg_type][0]
        rsi = TEXTURES / 'Small' / folder / 'zoomba.rsi'
        rsi.mkdir(parents=True)

        idle, lights, dark = dmi.take(icon), dmi.take(f'{icon}_l'), dmi.blank()
        states = [(body, idle), (f'{body}_e', lights), (f'{body}_e_r', dark), (f'{body}_l', dark),
                  (f'{body}_moving', dmi.take(icon, True)), (f'{body}_e_moving', dmi.take(f'{icon}_l', True)),
                  (f'{body}_e_r_moving', dark), (f'{body}_l_moving', dark), ('wreck', dmi.take(f'{icon}-wreck'))]
        missing = [state for state, taken in states if taken is None]
        if missing:
            raise SystemExit(f'{sheet} has nothing for {icon}: {missing}')

        meta = {
            'version': 1,
            'license': 'CC-BY-SA-3.0',
            'copyright': f'Taken from Meridian Rift at {SOURCE.format(sha=sha, folder=FOLDER, file=sheet)}',
            'size': {'x': dmi.width, 'y': dmi.height},
            'states': [write_state(rsi, state, frames, delays) for state, (frames, delays) in states],
        }
        (rsi / 'meta.json').write_text(json.dumps(meta, indent=2) + '\n', encoding='utf-8', newline='\n')

        subtype, dummy = f'WFBorgSkin{folder}Zoomba', f'WFBorgChassis{folder}Zoomba'
        path = rsi.relative_to(ROOT / 'Resources/Textures').as_posix()
        subtypes.append(f'- type: borgSubtype\n  id: {subtype}\n  parentBorgType: {borg_type}\n'
                        f'  spritePath: {path}\n  dummyPrototype: {dummy}\n\n'
                        f'- type: wfBorgSkin\n  id: {subtype}\n  animated: true\n  walks: true\n')
        chassis.append(f'- type: entity\n  id: {dummy}\n  parent: {PARENTS[borg_type]}\n'
                       f'  categories: [ HideSpawnMenu ]\n  components:\n  - type: BorgSwitchableSubtype\n'
                       f'    borgSubtype: {subtype}\n')
        names.append(f'ent-{dummy} = {name}\n')

    header = '# Generated by Tools/_WF/BorgSkins/zoomba.py; edit the skin table there.\n\n'
    (PROTOTYPES / 'zoomba_subtypes.yml').write_text(header + '\n'.join(subtypes), encoding='utf-8', newline='\n')
    (PROTOTYPES / 'zoomba_chassis.yml').write_text(header + '\n'.join(chassis), encoding='utf-8', newline='\n')
    (LOCALE / 'zoomba_chassis.ftl').write_text(header + ''.join(names), encoding='utf-8', newline='\n')
    print(f'{len(SKINS)} zoomba skins')


if __name__ == '__main__':
    main()
