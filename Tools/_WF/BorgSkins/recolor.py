#!/usr/bin/env python3
"""Recolours the converted borg skins into PDV and TSF variants.

    python Tools/_WF/BorgSkins/recolor.py

Reads the engineering, medical and security skins that convert.py and zoomba.py wrote and rebuilds, for each faction,
their RSIs under Resources/Textures/_WF/BorgSkins/<size>/<faction>, plus faction_subtypes.yml, faction_chassis.yml and
faction_chassis.ftl. Run it again after either. The mapping is colour to colour, so shading steps are kept: a
skin's main accent hue takes the faction's body ramp, every other colour becomes plain metal, and the eyes take the
faction's lamp hue. Near-black detail stays black whatever its tint, and the visor of a body listed in VISORED
becomes black glass. The poses have their lights painted in, as there is no eye layer to draw over them; those
colours take the lamp hue too, in the poses only. A body listed in TRIMMED has light strips drawn into it: those
move to its light states, frame for frame, so they glow with the eyes, and are painted into its poses. The dullahans are left out: their artists agreed to the port, not to recolours.
"""
import colorsys
import json
import re
import shutil
from collections import Counter
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[3]
TEXTURES = ROOT / 'Resources/Textures'
PROTOTYPES = ROOT / 'Resources/Prototypes/_WF/BorgSkins'
LOCALE = ROOT / 'Resources/Locale/en-US/_WF/BorgSkins'
SOURCES = ('subtypes.yml', 'zoomba_subtypes.yml')
HEADER = '# Generated by Tools/_WF/BorgSkins/recolor.py from the skins convert.py and zoomba.py wrote.\n'

# Body ramp, dark to light, and lamp hue in degrees, both sampled from the stock _Mono chassis.
FACTIONS = {
    'PDV': {'ramp': ['#332a1f', '#443c30', '#564c3d', '#746754', '#93836f'], 'lamp': 127},
    'TSF': {'ramp': ['#1f2432', '#2b3244', '#3f4962', '#535c76', '#6e7891'], 'lamp': 219},
}
# Source department -> (faction role, the source body state, the role's body state).
ROLES = {
    'Engineering': ('Engineer', 'engineer', 'engineer'),
    'Medical': ('Medical', 'medical', 'medical'),
    'Security': ('Assault', 'robot', 'assault'),
}
SKIPPED_BODIES = ('dullahan',)
VISORED = ('meka',)             # bodies whose face is a glass dome rather than plating
# Bodies with light strips or lamps drawn into the body, and how those are told from its plating.
TRIMMED = {
    'vale': 'pose',             # saturated colours in the hue of its pose lights
    'darkhound': 'bright',      # every bright saturated colour
    'hound': 'bright',
    'alina': 'eyes',            # bright saturated colours in the hue of its eyes
    'wyvern': 'other',          # bright saturated colours outside its main accent
    'c9_t7o': 'other',
    'k1_t7y': 'other',
}
UNTRIMMED = (('hound', 'Security'),)    # all accent, no strips
POSES = ('rest', 'sit', 'bellyup', 'wreck', 'tipped')
UNTOUCHED = ('credit',)

GREY_LO, GREY_HI = 0x26, 0x8c   # the stock chassis neutrals run #262626 to #787878; a little headroom for highlights
CHROMA = 0.22                   # below this saturation a colour counts as neutral
PLATING_LUM = 0x70              # neutrals at least this bright are plating, darker ones frame and joints
HUE_WIDTH = 0.09
DARK = 0.22                     # at or below this HSV value a colour is black detail, whatever its tint
VISOR_WIDTH = 0.035             # a visor's accent is told from the body's by at least this much hue
LIGHT_HUE = 0.04                # a pose colour this close in hue to the eyes can be a painted-in light
LIGHT_VALUE = 0.6               # and is at least this bright
LIGHT_STANDING = 0.15           # and has at most this share of the standing body next to its share of the poses,
LIGHT_STANDING_EYE = 0.5        # or this for a colour the eye layer itself uses
UNDER_EYES = 0.5                # a colour with this share of its standing pixels under the eye layer is a light
UNDER_VALUE = 0.4               # if it is at least this bright
TRIM_HUE = 0.02                 # a 'pose' light strip is this close in hue to a pose light
TRIM_SATURATION = 0.75          # and at least this saturated
TRIM_BRIGHT = (0.5, 0.55)       # the least saturation and value of any other light strip
GLASS = ['#08080a', '#101014', '#1a1a20', '#26262e']   # black visor glass, dark to light


def rgb(text):
    return tuple(int(text[i:i + 2], 16) for i in (1, 3, 5))


def lum(c):
    return 0.299 * c[0] + 0.587 * c[1] + 0.114 * c[2]


def hsv(c):
    return colorsys.rgb_to_hsv(c[0] / 255, c[1] / 255, c[2] / 255)


def ramp_at(ramp, t):
    t = min(max(t, 0.0), 1.0) * (len(ramp) - 1)
    i = min(int(t), len(ramp) - 2)
    return tuple(round(ramp[i][k] + (ramp[i + 1][k] - ramp[i][k]) * (t - i)) for k in range(3))


def hue_distance(a, b):
    d = abs(a - b) % 1.0
    return min(d, 1 - d)


def visor_colours(body, eyes):
    """The accent colours of the visor: the patch of one hue that the eyes sit on, grown from the pixels under them."""
    def accent(c):
        return hsv(c)[1] >= CHROMA and hsv(c)[2] > DARK

    width, height = min(body.width, eyes.width), min(body.height, eyes.height)
    body, eyes = body.load(), eyes.load()
    seeds = [(x, y) for y in range(height) for x in range(width) if eyes[x, y][3] and body[x, y][3]]
    bins = Counter(round(hsv(body[x, y][:3])[0] * 24) % 24 for x, y in seeds if accent(body[x, y][:3]))
    if not bins or sum(bins.values()) < 0.5 * len(seeds):
        return set()
    hue = max(bins, key=bins.get) / 24
    found, todo, seen = set(), list(seeds), set(seeds)
    while todo:
        x, y = todo.pop()
        c = body[x, y][:3]
        if not body[x, y][3] or not accent(c) or hue_distance(hsv(c)[0], hue) > VISOR_WIDTH:
            continue
        found.add(c)
        for nx, ny in ((x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)):
            if 0 <= nx < width and 0 <= ny < height and (nx, ny) not in seen:
                seen.add((nx, ny))
                todo.append((nx, ny))
    return found


def pose_lights(standing, posed, eyes):
    """The colours of the lights painted into the poses: eye-like colours the standing body hardly uses."""
    hues = {hsv(c)[0] for c in eyes if hsv(c)[1] >= CHROMA}
    # The standing body has the eye layer for its lights, so a painted-in light is a colour it hardly uses itself.
    scale = sum(posed.values()) / max(sum(standing.values()), 1)
    return {c for c, n in posed.items()
            if hsv(c)[1] >= CHROMA and hsv(c)[2] >= LIGHT_VALUE
            and any(hue_distance(hsv(c)[0], hue) <= LIGHT_HUE for hue in hues)
            and standing[c] * scale < (LIGHT_STANDING_EYE if c in eyes else LIGHT_STANDING) * n}


def eye_underpaint(src, pairs):
    """The body colours the eye layer mostly covers: the unlit paint under a glow, which a pose shows bare."""
    covered, total = Counter(), Counter()
    for body, eyes in pairs:
        body, eyes = Image.open(src / f'{body}.png').convert('RGBA'), Image.open(src / f'{eyes}.png').convert('RGBA')
        if body.size != eyes.size:
            continue
        for under, over in zip(body.getdata(), eyes.getdata()):
            if under[3]:
                total[under[:3]] += 1
                covered[under[:3]] += bool(over[3])
    return {c for c, n in covered.items()
            if n >= UNDER_EYES * total[c] and hsv(c)[1] >= CHROMA and hsv(c)[2] >= UNDER_VALUE}


def accent_hue(colours):
    """The hue most of a body's coloured pixels have, or None for a body with no colour."""
    bins = Counter()
    for c, n in colours.items():
        if hsv(c)[1] >= CHROMA and hsv(c)[2] > DARK:
            bins[round(hsv(c)[0] * 24) % 24] += n
    return max(bins, key=bins.get) / 24 if bins else None


def trim_lights(kind, standing, lights, eyes):
    """The colours of a standing body's light strips, by the rule TRIMMED gives the body."""
    def near(c, others, width):
        return any(hue_distance(hsv(c)[0], hsv(other)[0]) <= width for other in others)

    if kind == 'pose':
        return {c for c in standing
                if hsv(c)[1] >= TRIM_SATURATION and hsv(c)[2] >= LIGHT_VALUE and near(c, lights, TRIM_HUE)}
    bright = {c for c in standing if hsv(c)[1] >= TRIM_BRIGHT[0] and hsv(c)[2] >= TRIM_BRIGHT[1]}
    if kind == 'eyes':
        return {c for c in bright if near(c, [e for e in eyes if hsv(e)[1] >= CHROMA], LIGHT_HUE)}
    if kind == 'other':
        main = accent_hue(standing)
        return {c for c in bright if main is not None and hue_distance(hsv(c)[0], main) > HUE_WIDTH}
    return bright


def body_map(colours, faction, visor=()):
    """Maps every body colour (a Counter of RGB to pixel count) to its faction colour."""
    ramp = [rgb(c) for c in FACTIONS[faction]['ramp']]
    chromatic = {c: n for c, n in colours.items() if hsv(c)[1] >= CHROMA and hsv(c)[2] > DARK}
    main = accent_hue(colours)
    # A visor in the body's own accent is part of the body.
    glass = {c for c in visor if main is None or hue_distance(hsv(c)[0], main) > VISOR_WIDTH}
    primary = [c for c in chromatic
               if c not in glass and main is not None and hue_distance(hsv(c)[0], main) <= HUE_WIDTH]

    # A body that is mostly bare plating has too little accent to carry the faction: its light plating takes the ramp too.
    if sum(colours[c] for c in primary) < 0.3 * sum(colours.values()):
        primary += [c for c in colours if c not in primary and hsv(c)[1] < CHROMA and lum(c) >= PLATING_LUM]

    levels = [lum(c) for c in primary] or [0, 1]
    lo, hi = min(levels), max(levels)
    rest = [lum(c) for c in colours if c not in primary] or [0, 1]
    rest_lo, rest_hi = min(rest), max(rest)

    glass_ramp = [rgb(c) for c in GLASS]
    glass_levels = [lum(c) for c in glass] or [0, 1]
    mapped = {}
    for c in colours:
        if c in glass:
            mapped[c] = ramp_at(glass_ramp, (lum(c) - min(glass_levels)) / max(max(glass_levels) - min(glass_levels), 1))
            continue
        if c in primary:
            mapped[c] = ramp_at(ramp, (lum(c) - lo) / max(hi - lo, 1))
            continue
        # Other hues and neutrals become the faction's plain metal, squeezed into its value range.
        v = lum(c)
        if rest_hi > GREY_HI and v > GREY_LO:
            v = rest_lo + (v - rest_lo) * (GREY_HI - min(rest_lo, GREY_LO)) / max(rest_hi - rest_lo, 1)
        grey = round(min(max(v, 0), 255))
        mapped[c] = (grey, grey, grey)
    return mapped


def lamp_colour(c, faction):
    h, s, v = hsv(c)
    if s < 0.12:
        return c
    # Hue only: a lamp's own saturation steps are its shading.
    r, g, b = colorsys.hsv_to_rgb(FACTIONS[faction]['lamp'] / 360, s, v)
    return round(r * 255), round(g * 255), round(b * 255)


def repaint(image, colour_of):
    image = image.convert('RGBA')
    pixels = image.load()
    for y in range(image.height):
        for x in range(image.width):
            r, g, b, a = pixels[x, y]
            if a:
                pixels[x, y] = (*colour_of((r, g, b)), a)
    return image


def frame_directions(state):
    """The direction of each frame of a state, in sheet order."""
    if 'delays' in state:
        return [direction for direction, delays in enumerate(state['delays']) for _ in delays]
    return list(range(state.get('directions', 1)))


def frame_at(image, size, index):
    columns = image.width // size[0]
    x, y = index % columns * size[0], index // columns * size[1]
    return image.crop((x, y, x + size[0], y + size[1]))


def strip_lights(body, body_state, eyes, eye_state, size, trim, faction):
    """A light state laid out like the body state: the recoloured eyes plus the body's light strips, frame for frame."""
    body = body.convert('RGBA')
    out = Image.new('RGBA', body.size)
    directions = frame_directions(body_state)
    eye_directions = frame_directions(eye_state)
    columns = body.width // size[0]
    for index, direction in enumerate(directions):
        frame = Image.new('RGBA', size)
        if len(eye_directions) == len(directions):
            frame = frame_at(eyes, size, index)
        elif direction in eye_directions:
            # Eyes with fewer frames than the body hold still.
            frame = frame_at(eyes, size, eye_directions.index(direction))
        frame = repaint(frame, lambda c: lamp_colour(c, faction))
        lit, under = frame.load(), frame_at(body, size, index).load()
        for y in range(size[1]):
            for x in range(size[0]):
                r, g, b, a = under[x, y]
                if a and not lit[x, y][3] and (r, g, b) in trim:
                    lit[x, y] = (*lamp_colour((r, g, b), faction), a)
        out.paste(frame, (index % columns * size[0], index // columns * size[1]))
    return out


def recolour(src, dst, faction, source_state, role_state):
    """Writes the faction RSI. The faction borg types show <state>_l as both eyes and lamp, so it is the skin's eyes."""
    meta = json.loads((src / 'meta.json').read_text(encoding='utf-8'))
    by_name = {state['name']: state for state in meta['states']}
    # (source state, output state, is it a light layer)
    wanted = [(source_state, role_state, False), (f'{source_state}_e', f'{role_state}_l', True),
              (f'{source_state}_moving', f'{role_state}_moving', False),
              (f'{source_state}_e_moving', f'{role_state}_l_moving', True)]
    wanted += [(pose, pose, False) for pose in POSES + UNTOUCHED]
    wanted = [entry for entry in wanted if entry[0] in by_name]

    colours, standing, posed, eyes = Counter(), Counter(), Counter(), Counter()
    for source, _, light in wanted:
        if source in UNTOUCHED:
            continue
        into = eyes if light else posed if source in POSES else standing
        for count, pixel in Image.open(src / f'{source}.png').convert('RGBA').getcolors(1 << 20):
            if pixel[3]:
                into[pixel[:3]] += count
                if not light:
                    colours[pixel[:3]] += count
    lights = pose_lights(standing, posed, eyes)
    lights |= eye_underpaint(src, [(body, eye) for body, eye in ((source_state, f'{source_state}_e'),
                                   (f'{source_state}_moving', f'{source_state}_e_moving'))
                                   if body in by_name and eye in by_name])
    visor = set()
    if src.name.startswith(VISORED) and source_state in by_name and f'{source_state}_e' in by_name:
        visor = visor_colours(Image.open(src / f'{source_state}.png').convert('RGBA'),
                              Image.open(src / f'{source_state}_e.png').convert('RGBA'))
    mapped = body_map(colours, faction, visor)
    body = src.name[:-len('.rsi')]
    trim = set()
    if body in TRIMMED and (body, src.parent.name) not in UNTRIMMED:
        trim = trim_lights(TRIMMED[body], standing, lights, eyes)
    # Only in the poses: a pose light's colour in a walking frame is body shading, and lighting it there makes it
    # flash; a light strip there is in the light state instead, and dark with it.
    lit = {**mapped, **{c: lamp_colour(c, faction) for c in lights | trim}}
    size = (meta['size']['x'], meta['size']['y'])
    body_of = {f'{source_state}_e': source_state, f'{source_state}_e_moving': f'{source_state}_moving'}

    if dst.exists():
        shutil.rmtree(dst)
    dst.mkdir(parents=True)
    states = []
    for source, output, light in wanted:
        image = Image.open(src / f'{source}.png')
        if light and trim and body_of[source] in by_name:
            under = body_of[source]
            image = strip_lights(Image.open(src / f'{under}.png'), by_name[under], image.convert('RGBA'),
                                 by_name[source], size, trim, faction)
            image.save(dst / f'{output}.png')
            states.append({**by_name[under], 'name': output})
            continue
        if source not in UNTOUCHED:
            image = repaint(image, (lambda c: lamp_colour(c, faction)) if light
                            else (lambda c: lit.get(c, c)) if source in POSES else (lambda c: mapped.get(c, c)))
        image.save(dst / f'{output}.png')
        states.append({**by_name[source], 'name': output})
    meta['states'] = states
    meta['copyright'] += f', recoloured for the {faction} by Tools/_WF/BorgSkins/recolor.py'
    (dst / 'meta.json').write_text(json.dumps(meta, indent=2) + '\n', encoding='utf-8', newline='\n')


def main():
    blocks = []
    for file in SOURCES:
        blocks += (PROTOTYPES / file).read_text(encoding='utf-8').replace('\r\n', '\n').split('\n\n')
    extras = {}
    for block in blocks:
        if '- type: wfBorgSkin' in block:
            lines = block.strip().split('\n')
            extras[lines[1].split()[-1]] = lines[2:]
    names = {}
    for file in ('chassis.ftl', 'zoomba_chassis.ftl'):
        names.update(re.findall(r'^ent-(\S+) = (.+)$', (LOCALE / file).read_text(encoding='utf-8'), re.M))

    subtypes, chassis, locale = [], [], []
    for block in blocks:
        match = re.search(r'- type: borgSubtype\n  id: (\S+)\n.*\n  spritePath: (\S+)\n  dummyPrototype: (\S+)', block)
        if not match:
            continue
        source_id, path, source_dummy = match.groups()
        _, _, size, department, rsi = path.split('/')
        body = rsi[:-len('.rsi')]
        if department not in ROLES or body.startswith(SKIPPED_BODIES):
            continue
        role, source_state, role_state = ROLES[department]
        ident = source_id[len('WFBorgSkin' + department):]
        name = names[source_dummy].rsplit(' ', 2)[0]
        for faction in FACTIONS:
            target = f'_WF/BorgSkins/{size}/{faction}/{role}/{rsi}'
            recolour(TEXTURES / path, TEXTURES / target, faction, source_state, role_state)
            tag = f'{faction.capitalize()}{role}{ident}'
            subtypes.append(f'- type: borgSubtype\n  id: WFBorgSkin{tag}\n  parentBorgType: {faction.lower()}{role.lower()}\n'
                            f'  spritePath: {target}\n  dummyPrototype: WFBorgChassis{tag}\n\n'
                            f'- type: wfBorgSkin\n  id: WFBorgSkin{tag}\n' + '\n'.join(extras.get(source_id, [])) + '\n')
            chassis.append(f'- type: entity\n  id: WFBorgChassis{tag}\n  parent: {faction}BorgChassis{role}\n'
                           f'  categories: [ HideSpawnMenu ]\n  components:\n  - type: BorgSwitchableSubtype\n'
                           f'    borgSubtype: WFBorgSkin{tag}\n')
            locale.append(f'ent-WFBorgChassis{tag} = {name} {faction} {role.lower()} cyborg\n')

    for path, body in ((PROTOTYPES / 'faction_subtypes.yml', '\n'.join(subtypes)),
                       (PROTOTYPES / 'faction_chassis.yml', '\n'.join(chassis)),
                       (LOCALE / 'faction_chassis.ftl', ''.join(locale))):
        path.write_text(HEADER + '\n' + body, encoding='utf-8', newline='\n')
    print(f'{len(subtypes)} faction skins')


if __name__ == '__main__':
    main()
