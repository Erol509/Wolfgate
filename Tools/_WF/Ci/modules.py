# A comment opener somewhere before WOLFGATE on the line.
IN_COMMENT = re.compile(r"//|#|<!--|/\*|^\s*\*|^\s*;|(?:^|\s)--\s")
# What may sit right before a marker: a comment opener, or a separator after another fork's note ("HL change; ").
LEAD = re.compile(r"(?:(?:^|\s)(?://+|#+|<!--|/\*+|\*|;|--)|[,;>])\s*$")
# WOLFGATE right after a comment opener (or an old "End WOLFGATE"), so a remainder that doesn't parse is broken.
AFTER_OPENER = re.compile(r"(?:^|\s)(?://+|#+|<!--|/\*+)\s*(?:(?i:end|start)\s+)?$")

