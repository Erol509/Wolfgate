#!/usr/bin/env python3
"""Generates the Wolfgate module docs and checks the modularity rules in AGENTS.md.

A module is a first-level folder under one of the _WF roots, or an external module listed in modules.yml. Each module
README gets a generated section listing the module's files and the files outside _WF its WOLFGATE markers (and its
unmarked entries) edit; Docs/_WF/NONMODULAR.md lists the standalone edits: untagged markers and unmarked entries
without a module.

    python Tools/_WF/Ci/modules.py --write            regenerate the docs, creating missing READMEs
    python Tools/_WF/Ci/modules.py --check            fail if the docs are stale or a rule is broken
    python Tools/_WF/Ci/modules.py --pr-check <ref>   fail if an edit since <ref> outside _WF has no marker

Reports are cut to 20 lines per section; --all prints everything. Needs PyYAML (pip install pyyaml).
"""
